@dataclass(frozen=True, slots=True)
class ModalityContrast:
    """What adding an observation modality did to the baseline's worst-measured direction."""

    baseline_design_id: str
    augmented_design_id: str
    baseline_condition_number: float
    augmented_condition_number: float
    baseline_min_eigenvalue: float
    augmented_min_eigenvalue: float
    probed_direction: tuple[float, ...]
    baseline_directional_information: float
    augmented_directional_information: float
    information_gain_ratio: float
    verdict: ModalityVerdict
    routes_to: str

    def __post_init__(self) -> None:
        object.__setattr__(
            self, "probed_direction", tuple(float(value) for value in self.probed_direction)
        )
        if not isinstance(self.verdict, ModalityVerdict):
            raise TypeError("verdict must be a ModalityVerdict")

    def to_dict(self) -> dict[str, object]:
        """Return the JSON-able contrast record."""
        return {
            "baseline_design_id": self.baseline_design_id,
            "augmented_design_id": self.augmented_design_id,
            "baseline_condition_number": self.baseline_condition_number,
            "augmented_condition_number": self.augmented_condition_number,
            "baseline_min_eigenvalue": self.baseline_min_eigenvalue,
            "augmented_min_eigenvalue": self.augmented_min_eigenvalue,
            "parameter_names": list(PARAMETER_NAMES),
            "probed_direction": list(self.probed_direction),
            "baseline_directional_information": self.baseline_directional_information,
            "augmented_directional_information": self.augmented_directional_information,
            "information_gain_ratio": self.information_gain_ratio,
            "verdict": self.verdict.value,
            "routes_to": self.routes_to,
            "evidence_class": "oracle-only",
        }


def measure_modality_contrast(
    params: InverseParameters,
    scene: ImagingScene,
    baseline: ObservationDesign,
    augmented: ObservationDesign,
    *,
    lift_ratio_required: float,
    probe_direction: object | None = None,
    steps: Sequence[float] = JACOBIAN_LOG_STEPS,
) -> ModalityContrast:
    """Measure whether an added modality constrains the baseline's least-measured direction.

    The probed direction defaults to the baseline's own smallest-eigenvalue eigenvector — the
    degeneracy the baseline HAS, not one chosen after seeing the augmented result.  The gain ratio is
    ``d^T F_aug d / d^T F_base d`` along that fixed direction.

    Args:
        params: Operating point.
        scene: Known geometry and calibration.
        baseline: The design whose degeneracy is being probed.
        augmented: The design with an added focal plane or channel.
        lift_ratio_required: Declared factor by which the directional information must grow for the
            verdict to be ``LIFTED``.  Required, with no default.
        probe_direction: Optional explicit direction to probe instead of the baseline's worst.
        steps: Central-difference steps.

    Returns:
        The contrast record, whose ``routes_to`` names the expansion a failure opens.

    Raises:
        ValueError: If ``lift_ratio_required`` is not greater than one.
    """
    required = _positive_finite(lift_ratio_required, what="lift_ratio_required")
    if required <= 1.0:
        raise ValueError(
            "lift_ratio_required must exceed one; a modality that adds nothing is not a lift"
        )
    base_report = identifiability_report(
        params, scene, baseline, label=f"{baseline.design_id}@baseline", steps=steps
    )
    aug_report = identifiability_report(
        params, scene, augmented, label=f"{augmented.design_id}@augmented", steps=steps
    )
    if probe_direction is None:
        direction = np.asarray(base_report.eigenvectors[:, 0], dtype=np.float64)
    else:
        direction = _unit_vector(probe_direction, what="probe_direction")
    base_information = base_report.directional_information(direction)
    aug_information = aug_report.directional_information(direction)
    ratio = math.inf if base_information <= 0.0 else aug_information / base_information
    lifted = ratio >= required
    return ModalityContrast(
        baseline_design_id=baseline.design_id,
        augmented_design_id=augmented.design_id,
        baseline_condition_number=base_report.condition_number,
        augmented_condition_number=aug_report.condition_number,
        baseline_min_eigenvalue=base_report.smallest_eigenvalue,
        augmented_min_eigenvalue=aug_report.smallest_eigenvalue,
        probed_direction=tuple(float(value) for value in direction),
        baseline_directional_information=base_information,
        augmented_directional_information=aug_information,
        information_gain_ratio=ratio,
        verdict=ModalityVerdict.LIFTED if lifted else ModalityVerdict.NOT_LIFTED,
        routes_to=(
            "observation-design: this modality closes the direction"
            if lifted
            else "observation-design expansion: time-resolved, force, or intervention modality is "
            "still required for this direction; scope is NOT reduced"
        ),
    )


def measure_length_scale_degeneracy(
    scene: ImagingScene,
    design: ObservationDesign,
    *,
    base: InverseParameters,
    length_over_sigma: Sequence[float],
    steps: Sequence[float] = JACOBIAN_LOG_STEPS,
) -> tuple[dict[str, float], ...]:
    """Sweep segment length at fixed photon budget and measure the flux degeneracy as it appears.

    The photon budget ``density x length`` is held constant across the sweep so that brightness does
    not confound the shape measurement: only the resolvability ``L / s`` changes.  For each point the
    overlap between the Fisher's worst eigendirection and the declared
    :data:`FLUX_DEGENERACY_DIRECTION` is reported, together with the information the image carries
    ALONG that declared direction.  Reporting the sweep rather than one flattering point is the whole
    reason this function exists.

    Args:
        scene: Known geometry and calibration.
        design: Which frames are acquired.
        base: Operating point supplying the PSF width, background, depth, and photon budget.
        length_over_sigma: Ratios ``L / s0`` to visit, all positive.
        steps: Central-difference steps.

    Returns:
        One record per ratio, in the order given.
    """
    ratios = [
        _positive_finite(value, what="length_over_sigma entry") for value in length_over_sigma
    ]
    if not ratios:
        raise ValueError("length_over_sigma must contain at least one ratio")
    budget = base.total_photons
    records: list[dict[str, float]] = []
    for ratio in ratios:
        length = ratio * base.psf_sigma_um
        params = replace(base, length_um=length, linear_density=budget / length)
        report = identifiability_report(
            params, scene, design, label=f"length-sweep@{ratio:g}", steps=steps
        )
        worst = np.asarray(report.eigenvectors[:, 0], dtype=np.float64)
        second = np.asarray(report.eigenvectors[:, 1], dtype=np.float64)
        flux_information = report.directional_information(FLUX_DEGENERACY_DIRECTION)
        records.append(
            {
                "length_over_sigma": float(ratio),
                "length_um": float(length),
                "linear_density": float(budget / length),
                "smallest_eigenvalue": report.smallest_eigenvalue,
                "second_smallest_eigenvalue": float(report.eigenvalues[1]),
                "condition_number": report.condition_number,
                "flux_direction_information": flux_information,
                "flux_information_relative": flux_information / report.largest_eigenvalue,
                "worst_direction_flux_overlap": abs(float(worst @ FLUX_DEGENERACY_DIRECTION)),
                "second_direction_flux_overlap": abs(float(second @ FLUX_DEGENERACY_DIRECTION)),
            }
        )
    return tuple(records)


