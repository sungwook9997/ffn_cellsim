"""Sandbox S11: what is actually identifiable from a synthetic microscopy image alone.

WHY this module exists.  The master plan's adversarial audit A5 rejects ``image -> parameter point
prediction`` outright: different molecular parameters can produce the same image, so a point estimate
along a degenerate direction is a number with no information in it.  A rejection is only worth
something if the degeneracy is MEASURED rather than asserted, so this module closes a loop on
synthetic data with known truth — parameters -> geometry -> image (Lane D's pixel-integrated
renderer) -> posterior -> coverage against truth — and reports the Fisher spectrum of the image
likelihood, the near-null eigenvectors that ARE the degeneracies, and what happens to them when an
observation modality is added.

WHY log coordinates.  Four of the five parameters are positive scales (segment length, linear
emitter density, in-focus PSF width, background), and the degeneracy the plan predicts is
multiplicative: an unresolved segment contributes only its TOTAL flux ``density x length``, so the
degenerate direction is ``log density + log length = const``.  In log coordinates that direction is
the fixed unit vector ``(1, -1, 0, 0, 0)/sqrt(2)`` and can be compared against a measured eigenvector
without fitting anything.  The axial position ``z`` stays linear because it is signed.

WHY a second, EXACT degeneracy is expected.  In ``AxialModel.WIDEFIELD`` the only route by which
either the in-focus width ``s0`` or the depth ``z`` reaches the image is the defocused width
``s(z) = s0 sqrt(1 + ((z - z_f)/z_R)^2)``.  A single frame therefore measures one number where two
parameters live, and the null direction is available in closed form (see
:func:`analytic_defocus_null_direction`).  This is not an approximation that a finer grid would
remove; it is structural, and it is the cleanest possible demonstration that "the image is sharp" is
not the same statement as "the object is thin".  A second focal plane breaks it because
``s(z_f1)/s(z_f2)`` depends on ``z`` and not on ``s0`` — which is exactly the failure route the plan
demands: image nonidentifiability -> additional modality / observation design, never scope reduction.

WHY the likelihood is Gaussian-approximated.  The camera is Poisson photon noise plus Gaussian read
noise (Lane D's :func:`~aleph.virtual_cell.synthetic_microscopy.apply_camera_model`).  The Fisher
information used here is the mean-parameter part of the Gaussian approximation to that mixture,
``F = J^T diag(1/(mu + read^2)) J``, where the variance is held at the linearisation point.  The
neglected term is the derivative of the variance, which contributes ``O(1/(2 v^2)) (d v/d theta)^2``
— second order in the same quantity — and the quantisation variance ``1/12`` of the 1-photon digital
step is four orders below the pixel means used here.  The approximation is stated so that a reader
can bound it, not hidden.

WHY the identifiability report is built from the LIKELIHOOD Fisher and never from the posterior
precision.  Adding the prior precision makes every direction look constrained; that is the prior
speaking, not the image.  ``F`` answers "what did the image measure", ``F + Lambda`` answers "what do
I believe" — they are different operators and this module keeps them apart (they are also neither the
solver tangent nor the force Jacobian).

SELF-SCORING WARNING — this is a STRUCTURE test, not a biological validation.  Every image here is
generated by the same renderer family that is inverted, which is precisely adversarial-audit case A6:
inside one renderer family a perfect score is available for free and means nothing about a cell.  The
only defence offered is measured, not rhetorical: :func:`measure_renderer_mismatch` regenerates the
truth under a DIFFERENT forward assumption (an aliased point-chain renderer, and a mis-calibrated
axial Rayleigh range) and reports how far the posterior degrades and whether the coverage test
collapses.  That degradation is the honest ceiling on what the closed loop is worth.  Everything this
module produces is ``oracle-only``; :func:`register_sandbox_sources` is what structurally keeps it out
of the biological corpus, and the exclusion is transitive so the posterior is blocked two hops below
the renderer.

Sanity Gate (self-tested in tests/ac/virtual_cell/test_sandbox_inverse.py):
  * dimensional: ``linear_density [photons/um/s] x length [um] x exposure [s]`` is photons; the
    rendered frame total minus background equals that product to the PSF truncation loss, and the
    Fisher entries carry the reciprocal-squared units of their two parameters, so the log-coordinate
    block is dimensionless.
  * boundary: at ``z = z_focus`` the defocus derivative ``d ln s / d z`` vanishes identically, so the
    axial coordinate is unidentifiable at first order from an in-focus frame and the analytic null
    direction degenerates to pure ``z``.  The reference truth is deliberately placed OFF focus so the
    measured degeneracy is the ``(s0, z)`` mixture and not that boundary artefact.
  * conservation: adding a focal plane or a channel can only ADD information — the augmented Fisher
    minus the baseline Fisher is positive semidefinite, which is asserted rather than assumed, and it
    is why a modality can lift a degeneracy but never create one.
  * numerical: the Jacobian is a central difference in log coordinates; halving the step must leave
    the well-determined eigenvalues unchanged to ~1e-6 relative while the null eigenvalue moves by
    orders of magnitude, which is how "zero" is distinguished from "small" without over-claiming.
  * sign sense: the flux-degenerate direction has OPPOSITE signs on ``log_length_um`` and
    ``log_linear_density`` — a same-sign vector would be the total-brightness direction, which is the
    best-determined direction, not the worst.
  * measurement protocol: coverage is the frequency with which the nominal central credible interval
    of a draw from the declared prior contains the truth that generated the image, over an ensemble
    with a recorded seed; it is measured with Lane F's
    :func:`~aleph.virtual_cell.surrogate.measure_interval_coverage` and its binomial z-score, and a
    deliberately shrunk-sigma posterior is run as a negative control so the test is known to have
    teeth.

What this module MEASURED at the declared reference configuration (reproducible from the constants at
the foot of this file; the numbers live here because they are the deliverable, and every one of them
is ``oracle-only``):

* a single widefield frame has Fisher eigenvalues ``[2.5e-12, 0.89, 1.6e3, 5.6e3, 1.8e4]`` and a
  condition number of ``7.1e15``.  The smallest eigendirection overlaps
  :func:`analytic_defocus_null_direction` at ``|cos| = 1.0000`` — the ``(s0, z)`` degeneracy is exact
  — and the next one overlaps :data:`FLUX_DEGENERACY_DIRECTION` at ``0.9999`` at ``5.0e-5`` of the
  top eigenvalue.  Halving the differentiation step moves the null eigenvalue by 66 percent and the
  four determined ones by at most ``3.1e-8`` relative, which is how "zero" is told from "small".
* a second focal plane raises the information along that fixed null direction by ``2.5e15`` and the
  condition number falls to ``1.7e4`` — but it raises the FLUX direction only ``2.3x``, from 1.80 to
  4.10, which is still below the information the prior already carried.  An independently calibrated
  40 nm channel raises the flux direction ``41.8x`` to 75.1 and the condition number falls to 729.
  One modality lifted one degeneracy and not the other; that contrast is the observation-design
  result, and neither modality was chosen after seeing the other's number.
* holding the photon budget fixed and sweeping ``L/s0`` over ``0.25 ... 8``, the information along
  the flux direction relative to the best-measured direction runs ``4.3e-7, 6.7e-6, 1.0e-4, 1.3e-3,
  9.9e-3, 2.8e-2``.  It never reaches three percent: from ONE widefield frame, segment length and
  linear density are never cleanly separated at any scale in that range.
* calibration, 1000 draws from the declared prior, matched renderer, single plane: coverage of the
  nominal 95 percent interval is ``0.933, 0.940, 0.957, 0.938, 0.922`` in parameter order.  That is a
  REAL deficit of up to 2.8 points, significant at ``z = -4.1``, so the S11 falsifier fires in its
  weak form and the finding is recorded rather than smoothed: the Laplace posterior is approximately
  but not exactly calibrated, which routes to a nonlinear posterior sampler.  Shrinking the reported
  sigmas by half — the overconfident negative control — drops coverage to ``0.68 ... 0.75`` at
  ``|z| = 19``, so the test is known to have teeth.
* renderer mismatch, single plane: an aliased point-chain truth differs from the pixel-integrated one
  by ``1.8e-2`` relative and costs at most ``0.8`` coverage points; a 15 percent axial mis-calibration
  differs by ``4.8e-2`` and costs at most ``3.3`` points.  Both are ABSORBED, because the parameters
  that would have to move are degenerate anyway.  Run the same 15 percent mis-calibration against the
  TWO-PLANE design and coverage of ``log_psf_sigma_um`` falls ``0.950 -> 0.671`` and of ``z_um``
  ``0.929 -> 0.592``.  The modality that bought identifiability is exactly the one that bought
  exposure to forward-model error, and that trade is the honest ceiling on what this closed loop is
  worth.

References: Rao-Cramer identifiability of superresolution parameters, Ober et al. (2004) Biophys. J.
86, 1185; Zhang & Zhu (2007) Appl. Opt. 46, 1819 for the Gaussian widefield PSF and its axial
broadening (inherited from :mod:`aleph.virtual_cell.optics`).

Master plan: section 5.3 sandbox S11, section 10.2 audits A5 and A6.  This is deliberately NOT an
``Implements: KU-x.y`` line — no ratified ``ModelContract`` covers this sandbox, and inventing an
edge to one would be worse than having none.
"""

