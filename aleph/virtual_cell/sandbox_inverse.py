def register_sandbox_sources(registry: SourceRegistry | None = None) -> SourceRegistry:
    """Register this sandbox's synthetic ancestry so nothing here can be cited as biology.

    The chain is renderer -> image -> posterior -> identifiability report.  Because the renderer's
    origin is ``SYNTHETIC_RENDER``, every descendant inherits a transitive exclusion, so the Fisher
    spectrum — two hops below the renderer — is blocked without anyone having to remember to block
    it.  That transitivity is the structural answer to master-plan audit A6.

    Args:
        registry: Optional registry to extend; a fresh one is created when omitted.

    Returns:
        The registry, for chaining.
    """
    target = SourceRegistry() if registry is None else registry
