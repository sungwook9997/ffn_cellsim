@dataclass(frozen=True, slots=True)
class CoverageCampaign:
    """Measured calibration of the image posterior over an ensemble of synthetic truths."""

    label: str
    design_id: str
    truth_family: RendererFamily
    rayleigh_scale: float
    sigma_scale: float
    n_draws: int
    nominal_level: float
    seed: int
    per_parameter: Mapping[str, CoverageReport]
    mean_bias_in_sigma: Mapping[str, float]
    trust_region_hits: int = 0
    unconverged_draws: int = 0
    max_iterations_used: int = 1

    def __post_init__(self) -> None:
        if not isinstance(self.label, str) or not self.label.strip():
            raise ValueError("label must be a non-empty string")
        object.__setattr__(self, "label", self.label.strip())
        object.__setattr__(self, "per_parameter", MappingProxyType(dict(self.per_parameter)))
        object.__setattr__(
            self,
            "mean_bias_in_sigma",
            MappingProxyType({str(k): float(v) for k, v in self.mean_bias_in_sigma.items()}),
        )
        for name in ("trust_region_hits", "unconverged_draws"):
            value = getattr(self, name)
            if isinstance(value, bool) or not isinstance(value, int) or value < 0:
                raise ValueError(f"{name} must be a nonnegative integer")
        if (
            isinstance(self.max_iterations_used, bool)
            or not isinstance(self.max_iterations_used, int)
            or self.max_iterations_used < 1
        ):
            raise ValueError("max_iterations_used must be a positive integer")

    @property
    def worst_z_score(self) -> float:
        """Largest absolute binomial z-score over the parameters."""
        return max(abs(report.z_score) for report in self.per_parameter.values())

    @property
    def all_calibrated(self) -> bool:
        """Whether every parameter's interval passed the declared binomial sigma band."""
        return all(report.calibrated for report in self.per_parameter.values())

    @property
    def uncalibrated_parameters(self) -> tuple[str, ...]:
        """Parameters whose measured coverage falls outside the binomial band."""
        return tuple(
            sorted(name for name, report in self.per_parameter.items() if not report.calibrated)
        )

    def to_dict(self) -> dict[str, object]:
        """Return the JSON-able campaign record."""
        return {
            "label": self.label,
            "design_id": self.design_id,
            "truth_renderer_family": self.truth_family.value,
            "rayleigh_scale": self.rayleigh_scale,
            "sigma_scale": self.sigma_scale,
            "n_draws": self.n_draws,
            "nominal_level": self.nominal_level,
            "seed": self.seed,
            "coverage": {name: report.to_dict() for name, report in self.per_parameter.items()},
            "mean_bias_in_sigma": dict(self.mean_bias_in_sigma),
            "trust_region_hits": self.trust_region_hits,
            "unconverged_draws": self.unconverged_draws,
            "max_iterations_used": self.max_iterations_used,
            "all_calibrated": self.all_calibrated,
            "uncalibrated_parameters": list(self.uncalibrated_parameters),
            "self_scoring": self.truth_family is RendererFamily.PIXEL_INTEGRATED_LINE
            and self.rayleigh_scale == 1.0,
            "evidence_class": "oracle-only",
        }


def run_coverage_campaign(
    scene: ImagingScene,
    design: ObservationDesign,
    prior: GaussianLogPrior,
    *,
    n_draws: int,
    nominal_level: float,
    seed: int,
    label: str,
    truth_family: RendererFamily = RendererFamily.PIXEL_INTEGRATED_LINE,
    rayleigh_scale: float = 1.0,
    sigma_scale: float = 1.0,
    max_refinement_steps: int = 16,
    step_tolerance_prior_sigma: float = 1e-3,
    trust_radius_prior_sigma: float = 6.0,
    steps: Sequence[float] = JACOBIAN_LOG_STEPS,
) -> CoverageCampaign:
    """Measure how often the nominal credible interval contains the truth that made the image.

    Each draw takes a truth from the prior, renders it under ``truth_family`` (optionally with a
    mis-calibrated axial Rayleigh range), samples the camera, inverts with the PIXEL-INTEGRATED
    model, and records whether the truth fell inside each parameter's interval.  Coverage and its
    binomial z-score come from Lane F's :func:`measure_interval_coverage`; nothing is fitted here.

    Args:
        scene: Known geometry and calibration.
        design: Which frames are acquired.
        prior: The generative prior AND the inference prior — they must be the same object for the
            coverage statement to mean anything.
        n_draws: Ensemble size; the binomial standard error is
            ``sqrt(level (1 - level) / n_draws)``.
        nominal_level: Claimed central probability.
        seed: Recorded RNG seed; every number is reproducible from it.
        label: Human-readable campaign name.
        truth_family: Renderer used to GENERATE the truth image.  Anything other than
            ``PIXEL_INTEGRATED_LINE`` is a renderer-mismatch control.
        rayleigh_scale: Axial calibration error applied to the truth renderer only.
        sigma_scale: Multiplies every reported posterior sigma.  ``1.0`` is the posterior as
            derived; a value below one is a deliberately OVERCONFIDENT negative control, which is
            here so the coverage test is known to have teeth.
        max_refinement_steps: Iteration ceiling passed to :func:`infer_posterior`.
        step_tolerance_prior_sigma: Convergence tolerance passed to :func:`infer_posterior`.
        trust_radius_prior_sigma: Iterate box passed to :func:`infer_posterior`; the number of draws
            that touched it is reported on the result rather than swallowed.
        steps: Central-difference steps.

    Returns:
        The campaign result.

    Raises:
        ValueError: If ``n_draws`` is below two or ``sigma_scale`` is not positive-finite.
    """
    if isinstance(n_draws, bool) or not isinstance(n_draws, int) or n_draws < 2:
        raise ValueError("n_draws must be an integer of at least two")
    if isinstance(seed, bool) or not isinstance(seed, int) or seed < 0:
        raise ValueError("seed must be a nonnegative integer")
    scale = _positive_finite(sigma_scale, what="sigma_scale")
    rng = np.random.default_rng(seed)

    truths = np.empty((n_draws, _N_PARAMETERS), dtype=np.float64)
    means = np.empty_like(truths)
    sigmas = np.empty_like(truths)
    trust_region_hits = 0
    unconverged = 0
    max_iterations_used = 1
    for draw in range(n_draws):
        truth_vector = prior.draw(rng)
        truth = InverseParameters.from_vector(truth_vector)
        expected = expected_photons(
            truth, scene, design, family=truth_family, rayleigh_scale=rayleigh_scale
        )
        camera_seed = int(rng.integers(0, 2**31 - 1))
        observed = sample_observation(expected, scene, seed=camera_seed)
        posterior = infer_posterior(
            observed,
            scene,
            design,
            prior,
            max_refinement_steps=max_refinement_steps,
            step_tolerance_prior_sigma=step_tolerance_prior_sigma,
            trust_radius_prior_sigma=trust_radius_prior_sigma,
            steps=steps,
        )
        trust_region_hits += int(posterior.trust_region_active)
        unconverged += int(not posterior.converged)
        max_iterations_used = max(max_iterations_used, posterior.iterations)
        truths[draw] = truth_vector
        means[draw] = posterior.mean
        sigmas[draw] = [posterior.marginal_sigma(name) * scale for name in PARAMETER_NAMES]

    reports: dict[str, CoverageReport] = {}
    biases: dict[str, float] = {}
    for index, name in enumerate(PARAMETER_NAMES):
        reports[name] = measure_interval_coverage(
            truths[:, index],
            means[:, index],
            sigmas[:, index],
            nominal_level=nominal_level,
            seed=seed,
            label=f"{label}:{name}",
        )
        biases[name] = float(np.mean((means[:, index] - truths[:, index]) / sigmas[:, index]))
    return CoverageCampaign(
        label=label,
        design_id=design.design_id,
        truth_family=truth_family,
        rayleigh_scale=float(rayleigh_scale),
        sigma_scale=scale,
        n_draws=int(n_draws),
        nominal_level=float(nominal_level),
        seed=int(seed),
        per_parameter=reports,
        mean_bias_in_sigma=biases,
        trust_region_hits=trust_region_hits,
        unconverged_draws=unconverged,
        max_iterations_used=max_iterations_used,
    )


