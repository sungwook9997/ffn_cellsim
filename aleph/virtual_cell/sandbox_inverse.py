@dataclass(frozen=True, slots=True)
class ImageInversePosterior:
    """Linear-Gaussian posterior over :data:`PARAMETER_NAMES`, with A5 enforced structurally.

    :meth:`credible_interval` is always available — an honest interval is the correct answer for an
    unidentifiable parameter, and it will simply be as wide as the prior.  :meth:`point_estimate`
    REFUSES when the requested parameter's identifiable fraction falls below the caller's declared
    requirement.  That refusal is the master plan's A5 verdict expressed as code rather than prose:
    a caller who receives a number will use it, so no number is returned.
    """

    mean: np.ndarray
    covariance: np.ndarray
    identifiability: IdentifiabilityReport
    prior: GaussianLogPrior
    design_id: str
    renderer_family: RendererFamily
    iterations: int
    converged: bool
    trust_region_active: bool = False

    def __post_init__(self) -> None:
        mean = np.asarray(self.mean, dtype=np.float64).reshape(-1).copy()
        if mean.size != _N_PARAMETERS or not np.all(np.isfinite(mean)):
            raise ValueError(f"mean must be finite with length {_N_PARAMETERS}")
        mean.setflags(write=False)
        object.__setattr__(self, "mean", mean)
        covariance = np.asarray(self.covariance, dtype=np.float64).copy()
        if covariance.shape != (_N_PARAMETERS, _N_PARAMETERS) or not np.all(
            np.isfinite(covariance)
        ):
            raise ValueError("covariance must be a finite (5, 5) matrix")
        if np.any(np.diag(covariance) <= 0.0):
            raise ValueError("covariance must have positive diagonal")
        covariance.setflags(write=False)
        object.__setattr__(self, "covariance", covariance)
        if not isinstance(self.identifiability, IdentifiabilityReport):
            raise TypeError("identifiability must be an IdentifiabilityReport")
        if not isinstance(self.prior, GaussianLogPrior):
            raise TypeError("prior must be a GaussianLogPrior")
        if not isinstance(self.renderer_family, RendererFamily):
            raise TypeError("renderer_family must be a RendererFamily")
        if (
            isinstance(self.iterations, bool)
            or not isinstance(self.iterations, int)
            or self.iterations < 1
        ):
            raise ValueError("iterations must be a positive integer")
        for name in ("converged", "trust_region_active"):
            if not isinstance(getattr(self, name), bool):
                raise TypeError(f"{name} must be a bool")

    def marginal_sigma(self, parameter: str) -> float:
        """Posterior standard deviation of one parameter."""
        index = _parameter_index(parameter)
        return math.sqrt(float(self.covariance[index, index]))

    def credible_interval(self, parameter: str, *, level: float) -> tuple[float, float]:
        """Central credible interval — always available, even for an unidentifiable parameter.

        Args:
            parameter: One of :data:`PARAMETER_NAMES`.
            level: Central probability in ``(0, 1)``.

        Returns:
            ``(low, high)`` in the parameter's own coordinate.
        """
        if not 0.0 < _finite(level, what="level") < 1.0:
            raise ValueError("level must lie strictly inside (0, 1)")
        index = _parameter_index(parameter)
        from statistics import NormalDist

        half = NormalDist().inv_cdf(0.5 + level / 2.0) * self.marginal_sigma(parameter)
        centre = float(self.mean[index])
        return (centre - half, centre + half)

    def point_estimate(
        self,
        parameter: str,
        *,
        eigenvalue_floor: float,
        min_identifiable_fraction: float,
    ) -> float:
        """Return a point estimate, or REFUSE because the image did not measure this parameter.

        Args:
            parameter: One of :data:`PARAMETER_NAMES`.
            eigenvalue_floor: Absolute Fisher information below which a direction is unmeasured.
            min_identifiable_fraction: How much of the parameter's unit vector must lie in the
                measured subspace.  Both are required with no default: choosing them is a contract
                the caller writes before the run, not a knob this module tunes afterwards.

        Returns:
            The posterior mean of the parameter.

        Raises:
            UnidentifiableDirectionError: If the identifiable fraction is below the requirement.
        """
        if not 0.0 < _finite(min_identifiable_fraction, what="min_identifiable_fraction") <= 1.0:
            raise ValueError("min_identifiable_fraction must lie in (0, 1]")
        index = _parameter_index(parameter)
        fraction = self.identifiability.identifiable_fraction(
            parameter, eigenvalue_floor=eigenvalue_floor
        )
        if fraction < min_identifiable_fraction:
            raise UnidentifiableDirectionError(
                f"{parameter!r} is not identifiable from design {self.design_id!r}: "
                f"identifiable fraction {fraction:.4g} < required {min_identifiable_fraction:.4g} at "
                f"eigenvalue floor {eigenvalue_floor:.4g}. Master-plan A5 rejects image->parameter "
                f"point prediction along an unmeasured direction; use credible_interval, or add an "
                f"observation modality (see measure_modality_contrast)."
            )
        return float(self.mean[index])

    def estimate_along(
        self,
        direction: object,
        *,
        eigenvalue_floor: float,
    ) -> float:
        """Return the posterior mean projected on a direction, or refuse if it is unmeasured.

        Args:
            direction: Any length-5 vector, normalised internally.
            eigenvalue_floor: Information floor the direction's ``d^T F d`` must reach.

        Returns:
            ``d . mean``.

        Raises:
            UnidentifiableDirectionError: If ``d^T F d`` is below the floor.
        """
        unit = _unit_vector(direction, what="direction")
        floor = _positive_finite(eigenvalue_floor, what="eigenvalue_floor")
        information = self.identifiability.directional_information(unit)
        if information < floor:
            raise UnidentifiableDirectionError(
                f"direction carries Fisher information {information:.6g} < floor {floor:.6g} under "
                f"design {self.design_id!r}; no point estimate is available along it"
            )
        return float(unit @ self.mean)

    def to_dict(self, *, eigenvalue_floor: float) -> dict[str, object]:
        """Return the JSON-able posterior record."""
        return {
            "design_id": self.design_id,
            "renderer_family": self.renderer_family.value,
            "iterations": self.iterations,
            "converged": self.converged,
            "trust_region_active": self.trust_region_active,
            "parameter_names": list(PARAMETER_NAMES),
            "mean": [float(value) for value in self.mean],
            "marginal_sigma": [self.marginal_sigma(name) for name in PARAMETER_NAMES],
            "identifiability": self.identifiability.to_dict(eigenvalue_floor=eigenvalue_floor),
            "prior": self.prior.to_dict(),
            "self_scoring": True,
            "evidence_class": "oracle-only",
        }


def infer_posterior(
    observation: np.ndarray,
    scene: ImagingScene,
    design: ObservationDesign,
    prior: GaussianLogPrior,
    *,
    max_refinement_steps: int = 16,
    step_tolerance_prior_sigma: float = 1e-3,
    trust_radius_prior_sigma: float = 6.0,
    steps: Sequence[float] = JACOBIAN_LOG_STEPS,
) -> ImageInversePosterior:
    """Invert one noisy frame stack to a linear-Gaussian posterior.

    The estimator is Fisher scoring on the Gaussian-approximated Poisson likelihood, started at the
    prior mean; for an identity-link Poisson model that iteration IS iteratively reweighted least
    squares, so at convergence it lands on the MAP and not merely near it.  The reported covariance
    is ``(F + Lambda)^-1`` at the final linearisation point.  With ``max_refinement_steps = 0`` the
    posterior is EXACT for the model linearised at the prior mean, which is how a coverage deficit
    caused by stopping early can be separated from one caused by non-Gaussianity — the first
    measurement this module made showed the wide-prior deficit was ENTIRELY the former.

    The iterate is confined to a box ``trust_radius_prior_sigma`` prior standard deviations wide
    around the prior mean.  This is not a convenience: along a degenerate direction the Gauss-Newton
    update is governed almost entirely by curvature the image does not have, so an occasional draw
    runs away to a segment hundreds of micrometres long, which is neither a posterior nor a
    renderable object.  A hit is RECORDED on :attr:`ImageInversePosterior.trust_region_active` and
    counted by :func:`run_coverage_campaign`, so a coverage number that depends on clipping is
    visible instead of silent.  The default radius is far outside where truths drawn from the prior
    live (a 5-D Gaussian's worst coordinate over a few hundred draws sits near three sigma), so it
    catches divergence and nothing else.

    The returned :attr:`ImageInversePosterior.identifiability` is built from the LIKELIHOOD Fisher
    only, so the prior cannot make a degenerate direction look measured.

    Args:
        observation: Observed photon counts, shaped like :func:`expected_photons` output.
        scene: Known geometry and calibration.
        design: Which frames were acquired.
        prior: Proper Gaussian prior in log coordinates.
        max_refinement_steps: Maximum re-linearisations after the first update.  The loop stops
            early once the step is below the tolerance, so this is a ceiling, not a cost.
        step_tolerance_prior_sigma: Convergence tolerance on the largest coordinate of the step,
            measured in prior standard deviations.
        trust_radius_prior_sigma: Half-width of the iterate box in prior standard deviations.
        steps: Central-difference steps.

    Returns:
        The posterior, carrying the iteration count and whether it converged.

    Raises:
        ValueError: If the observation shape disagrees with the design.
    """
    if not isinstance(prior, GaussianLogPrior):
        raise TypeError("prior must be a GaussianLogPrior")
    if (
        isinstance(max_refinement_steps, bool)
        or not isinstance(max_refinement_steps, int)
        or max_refinement_steps < 0
    ):
        raise ValueError("max_refinement_steps must be a nonnegative integer")
    tolerance = _positive_finite(step_tolerance_prior_sigma, what="step_tolerance_prior_sigma")
    radius = _positive_finite(trust_radius_prior_sigma, what="trust_radius_prior_sigma")
    data = np.asarray(observation, dtype=np.float64)
    expected_shape = (design.n_frames, scene.height_px, scene.width_px)
    if data.shape != expected_shape:
        raise ValueError(f"observation must have shape {expected_shape}, got {data.shape}")
    flat = data.reshape(-1)
    prior_precision = np.diag(1.0 / np.square(prior.sigma))

    lower = prior.mean - radius * prior.sigma
    upper = prior.mean + radius * prior.sigma

    def objective(vector: np.ndarray, weights: np.ndarray) -> float:
        """Penalised weighted sum of squares at FROZEN weights.

        The weights are held at the outer iterate, which is what makes the Fisher-scoring step a
        descent direction for this function and therefore makes backtracking guaranteed to succeed.
        The ``ln v`` term of the full Gaussian negative log-likelihood is deliberately absent: its
        gradient is not part of the quasi-score whose root this iteration seeks, and including it
        would have the line search fight the step it is supposed to shorten.
        """
        mean_image = expected_photons(InverseParameters.from_vector(vector), scene, design).reshape(
            -1
        )
        deviation = vector - prior.mean
        return float(
            0.5 * np.sum(np.square(flat - mean_image) * weights)
            + 0.5 * np.sum(np.square(deviation / prior.sigma))
        )

    current = prior.mean.copy()
    linearisation = prior.mean.copy()
    clipped = False
    converged = False
    iterations = 0
    for _ in range(max_refinement_steps + 1):
        iterations += 1
        point = InverseParameters.from_vector(linearisation)
        jacobian = model_jacobian(point, scene, design, steps=steps)
        mean_image = expected_photons(point, scene, design).reshape(-1)
        variance = mean_image + scene.read_variance_photons2
        weighted = jacobian / variance[:, None]
        fisher = jacobian.T @ weighted
        fisher = 0.5 * (fisher + fisher.T)
        precision = fisher + prior_precision
        residual = flat - mean_image
        gradient = weighted.T @ residual + prior_precision @ (prior.mean - linearisation)
        full_step = np.linalg.solve(precision, gradient)
        # The Newton step itself is the convergence criterion: it is the distance to the optimum of
        # the local quadratic model, so testing it BEFORE the line search avoids declaring a draw
        # unconverged merely because a step at round-off scale failed to lower the objective.
        if float(np.max(np.abs(full_step / prior.sigma))) < tolerance:
            converged = True
            break
        # Backtracking on the same objective the step is trying to reduce.  Fisher scoring along a
        # nearly singular direction can overshoot and cycle; halving until the objective actually
        # decreases turns those draws into slow ones instead of wrong ones, and a draw that never
        # finds a decrease is reported as unconverged rather than silently accepted.
        weights = 1.0 / variance
        anchor = objective(linearisation, weights)
        damping = 1.0
        accepted = False
        for _ in range(_LINE_SEARCH_HALVINGS):
            proposal = np.clip(linearisation + damping * full_step, lower, upper)
            if objective(proposal, weights) <= anchor:
                accepted = True
                break
            damping *= 0.5
        if not accepted:
            break
        clipped = clipped or bool(np.any(proposal != linearisation + damping * full_step))
        linearisation = proposal
        current = proposal

    final_point = InverseParameters.from_vector(current)
    likelihood_fisher = fisher_information(final_point, scene, design, steps=steps)
    covariance = np.linalg.inv(likelihood_fisher + prior_precision)
    covariance = 0.5 * (covariance + covariance.T)
    eigenvalues, eigenvectors = np.linalg.eigh(likelihood_fisher)
    report = IdentifiabilityReport(
        label=f"{design.design_id}@posterior",
        fisher=likelihood_fisher,
        eigenvalues=eigenvalues,
        eigenvectors=eigenvectors,
        candidate_directions={
            "flux": tuple(float(value) for value in FLUX_DEGENERACY_DIRECTION),
            "analytic-defocus": tuple(
                float(value)
                for value in analytic_defocus_null_direction(
                    final_point, scene, design.focal_planes_um[0]
                )
            ),
        },
    )
    return ImageInversePosterior(
        mean=current,
        covariance=covariance,
        identifiability=report,
        prior=prior,
        design_id=design.design_id,
        renderer_family=RendererFamily.PIXEL_INTEGRATED_LINE,
        iterations=iterations,
        converged=converged,
        trust_region_active=clipped,
    )


