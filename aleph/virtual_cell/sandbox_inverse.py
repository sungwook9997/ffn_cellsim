def _segment_endpoints(
    params: InverseParameters, scene: ImagingScene
) -> tuple[tuple[float, float], tuple[float, float]]:
    half = 0.5 * params.length_um
    dx = half * math.cos(scene.orientation_rad)
    dy = half * math.sin(scene.orientation_rad)
    cx, cy = scene.centre_xy_um
    return (cx - dx, cy - dy), (cx + dx, cy + dy)


def _emitters(
    params: InverseParameters, scene: ImagingScene, family: RendererFamily
) -> tuple[Sequence[Emitter], PSFSampling]:
    start, end = _segment_endpoints(params, scene)
    if family is RendererFamily.PIXEL_INTEGRATED_LINE:
        line = LineEmitter(
            start_xy_um=start,
            end_xy_um=end,
            photon_rate_per_length=params.linear_density,
            z_um=params.z_um,
        )
        return (line,), PSFSampling.PIXEL_INTEGRATED
    if family is RendererFamily.ALIASED_POINT_CHAIN:
        count = scene.point_chain_labels
        share = params.total_photons / count
        # Midpoint sampling of the segment: the labels tile the segment rather than sitting on its
        # endpoints, so the discretised first moment matches the continuous one exactly.
        fractions = (np.arange(count, dtype=np.float64) + 0.5) / count
        points = [
            (
                start[0] + fraction * (end[0] - start[0]),
                start[1] + fraction * (end[1] - start[1]),
            )
            for fraction in fractions
        ]
        labels = tuple(
            PointEmitter(xy_um=point, photon_rate=share, z_um=params.z_um) for point in points
        )
        return labels, PSFSampling.POINT_SAMPLED
    raise TypeError(f"unsupported renderer family: {family!r}")


def _frame(
    params: InverseParameters,
    scene: ImagingScene,
    *,
    sigma_um: float,
    focal_plane_um: float,
    rayleigh_range_um: float,
    family: RendererFamily,
) -> np.ndarray:
    microscopy = MicroscopyConfig(
        height_px=scene.height_px,
        width_px=scene.width_px,
        pixel_size_um=scene.pixel_size_um,
        psf_sigma_um=sigma_um,
        background=params.background_photons,
        psf_radius_sigma=scene.psf_radius_sigma,
        world_y_direction="up",
    )
    emitters, sampling = _emitters(params, scene, family)
    optics = OpticsConfig(
        microscopy=microscopy,
        sampling=sampling,
        truncation=TruncationPolicy.ANALYTIC,
        axial_model=AxialModel.WIDEFIELD,
        rayleigh_range_um=rayleigh_range_um,
        focal_plane_z_um=focal_plane_um,
        exposure_s=scene.exposure_s,
        pixel_quadrature_nodes=scene.pixel_quadrature_nodes,
    )
    return render_emitters(emitters, optics, origin_xy_um=(0.0, 0.0))


def expected_photons(
    params: InverseParameters,
    scene: ImagingScene,
    design: ObservationDesign,
    *,
    family: RendererFamily = RendererFamily.PIXEL_INTEGRATED_LINE,
    rayleigh_scale: float = 1.0,
) -> np.ndarray:
    """Render the expected-photon stack this design would acquire.

    Args:
        params: The five inferred parameters.
        scene: Known geometry, exposure, and camera calibration.
        design: Which frames are acquired.
        family: Which forward assumption to render under.  The inversion always assumes
            :attr:`RendererFamily.PIXEL_INTEGRATED_LINE`; anything else is a mismatch control.
        rayleigh_scale: Multiplies the scene's axial Rayleigh range.  ``1.0`` is the inversion's
            assumption; another value is a declared axial mis-calibration, which is a forward-model
            error the parameter set cannot absorb once more than one focal plane is acquired.

    Returns:
        Read-only ``(n_frames, height_px, width_px)`` array of expected photons per pixel.

    Raises:
        TypeError: If any argument has the wrong type.
        ValueError: If ``rayleigh_scale`` is not positive-finite.
    """
    if not isinstance(params, InverseParameters):
        raise TypeError("params must be an InverseParameters")
    if not isinstance(scene, ImagingScene):
        raise TypeError("scene must be an ImagingScene")
    if not isinstance(design, ObservationDesign):
        raise TypeError("design must be an ObservationDesign")
    if not isinstance(family, RendererFamily):
        raise TypeError("family must be a RendererFamily")
    scale = _positive_finite(rayleigh_scale, what="rayleigh_scale")
    frames: list[np.ndarray] = []
    for plane in design.focal_planes_um:
        frames.append(
            _frame(
                params,
                scene,
                sigma_um=params.psf_sigma_um,
                focal_plane_um=plane,
                rayleigh_range_um=scene.rayleigh_range_um * scale,
                family=family,
            )
        )
    if design.extra_channel_sigma_um is not None:
        extra_rayleigh = (
            scene.rayleigh_range_um
            if design.extra_channel_rayleigh_range_um is None
            else design.extra_channel_rayleigh_range_um
        )
        frames.append(
            _frame(
                params,
                scene,
                sigma_um=design.extra_channel_sigma_um,
                focal_plane_um=design.extra_channel_focal_plane_um,
                rayleigh_range_um=extra_rayleigh * scale,
                family=family,
            )
        )
    stack = np.stack(frames, axis=0)
    stack.setflags(write=False)
    return stack


def sample_observation(
    expected: np.ndarray,
    scene: ImagingScene,
    *,
    seed: int,
) -> np.ndarray:
    """Draw one noisy frame stack through Lane D's camera model.

    Photon shot noise, read noise, saturation, and quantisation all come from
    :func:`~aleph.virtual_cell.synthetic_microscopy.apply_camera_model`.  The scene's camera runs at
    unit gain with a one-photon digital step, so the returned counts are photons and the Gaussian
    likelihood used for inference does not need a gain conversion.

    Args:
        expected: Expected-photon stack from :func:`expected_photons`.
        scene: Supplies the camera configuration.
        seed: Replay seed, recorded by every campaign.

    Returns:
        Float64 array of observed photon counts with the shape of ``expected``.
    """
    if not isinstance(scene, ImagingScene):
        raise TypeError("scene must be an ImagingScene")
    digital = apply_camera_model(expected, scene.camera, seed=seed)
    counts = np.asarray(digital, dtype=np.float64) * (
        scene.saturation_photons / float((1 << scene.bit_depth) - 1)
    )
    counts.setflags(write=False)
    return counts


def model_jacobian(
    params: InverseParameters,
    scene: ImagingScene,
    design: ObservationDesign,
    *,
    steps: Sequence[float] = JACOBIAN_LOG_STEPS,
) -> np.ndarray:
    """Central-difference Jacobian of the expected image in :data:`PARAMETER_NAMES` coordinates.

    Args:
        params: Linearisation point.
        scene: Known geometry and calibration.
        design: Which frames are acquired.
        steps: Per-parameter central-difference steps.

    Returns:
        Read-only ``(n_pixels, 5)`` array, where ``n_pixels`` is the flattened frame stack.

    Raises:
        ValueError: If ``steps`` does not have one positive-finite entry per parameter.
    """
    step_vector = np.asarray(steps, dtype=np.float64).reshape(-1)
    if step_vector.size != _N_PARAMETERS or np.any(step_vector <= 0.0):
        raise ValueError(f"steps must be {_N_PARAMETERS} positive-finite entries")
    if not np.all(np.isfinite(step_vector)):
        raise ValueError("steps must be finite")
    centre = params.to_vector()
    columns: list[np.ndarray] = []
    for index in range(_N_PARAMETERS):
        step = float(step_vector[index])
        forward = centre.copy()
        forward[index] += step
        backward = centre.copy()
        backward[index] -= step
        plus = expected_photons(InverseParameters.from_vector(forward), scene, design)
        minus = expected_photons(InverseParameters.from_vector(backward), scene, design)
        columns.append(((plus - minus) / (2.0 * step)).reshape(-1))
    jacobian = np.stack(columns, axis=1)
    jacobian.setflags(write=False)
    return jacobian


def fisher_information(
    params: InverseParameters,
    scene: ImagingScene,
    design: ObservationDesign,
    *,
    steps: Sequence[float] = JACOBIAN_LOG_STEPS,
) -> np.ndarray:
    """Gaussian-approximated Fisher information of the image likelihood.

    ``F = J^T diag(1/(mu + read^2)) J`` with the variance held at ``params`` — the mean-parameter part
    of the Poisson-plus-read-noise information.  This is the LIKELIHOOD information: no prior, so a
    zero eigenvalue means the image measured nothing along that direction.

    Args:
        params: Point at which the information is evaluated.
        scene: Supplies the read-noise variance.
        design: Which frames are acquired.
        steps: Central-difference steps passed to :func:`model_jacobian`.

    Returns:
        Read-only symmetric ``(5, 5)`` matrix.
    """
    jacobian = model_jacobian(params, scene, design, steps=steps)
    mean = expected_photons(params, scene, design).reshape(-1)
    variance = mean + scene.read_variance_photons2
    if np.any(variance <= 0.0):
        raise ValueError(
            "pixel variance must be positive; a zero-background noiseless camera is not a likelihood"
        )
    weighted = jacobian / variance[:, None]
    fisher = jacobian.T @ weighted
    fisher = 0.5 * (fisher + fisher.T)
    fisher.setflags(write=False)
    return fisher


def analytic_defocus_null_direction(
    params: InverseParameters,
    scene: ImagingScene,
    focal_plane_um: float,
) -> np.ndarray:
    """Closed-form null direction of a SINGLE widefield frame in ``(log s0, z)``.

    Both parameters reach the image only through ``s(z) = s0 sqrt(1 + ((z - z_f)/z_R)^2)``, so the
    direction along which ``ln s`` is stationary is exactly unmeasured by that frame.  With
    ``d = z - z_f``, ``d ln s / d ln s0 = 1`` and ``d ln s / d z = d / (z_R^2 + d^2)``, so the null
    direction is ``(0, 0, -d/(z_R^2 + d^2), 0, 1)`` normalised.

    Args:
        params: Supplies the true depth.
        scene: Supplies the Rayleigh range.
        focal_plane_um: The frame's focal plane.

    Returns:
        Read-only unit vector in :data:`PARAMETER_NAMES` coordinates.
    """
    if not isinstance(params, InverseParameters):
        raise TypeError("params must be an InverseParameters")
    if not isinstance(scene, ImagingScene):
        raise TypeError("scene must be an ImagingScene")
    defocus = params.z_um - _finite(focal_plane_um, what="focal_plane_um")
    slope = defocus / (scene.rayleigh_range_um**2 + defocus**2)
    direction = np.array([0.0, 0.0, -slope, 0.0, 1.0], dtype=np.float64)
    direction = direction / float(np.linalg.norm(direction))
    direction.setflags(write=False)
    return direction


# The degeneracies declared BEFORE any measurement.  ``analytic-defocus`` needs the operating point,
# so it is a callable; ``flux`` is a fixed vector in log coordinates.
CANDIDATE_DEGENERACIES: Mapping[str, str] = MappingProxyType(
    {
        "flux": "log_linear_density + log_length_um constant (unresolved segment carries only its "
        "photon budget)",
        "analytic-defocus": "log_psf_sigma_um and z_um traded so the defocused width s(z) is "
        "unchanged (single widefield frame measures one width, not two parameters)",
    }
)


