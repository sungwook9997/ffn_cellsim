@dataclass(frozen=True, slots=True)
class NullDirection:
    """One measured near-null eigendirection of the image Fisher information."""

    eigenvalue: float
    relative_eigenvalue: float
    direction: tuple[float, ...]
    dominant_parameters: tuple[str, ...]
    candidate_overlaps: Mapping[str, float]

    def __post_init__(self) -> None:
        object.__setattr__(
            self, "eigenvalue", _nonnegative_finite(self.eigenvalue, what="eigenvalue")
        )
        object.__setattr__(
            self,
            "relative_eigenvalue",
            _nonnegative_finite(self.relative_eigenvalue, what="relative_eigenvalue"),
        )
        direction = tuple(float(value) for value in self.direction)
        if len(direction) != _N_PARAMETERS:
            raise ValueError(f"direction must have length {_N_PARAMETERS}")
        object.__setattr__(self, "direction", direction)
        object.__setattr__(self, "dominant_parameters", tuple(self.dominant_parameters))
        object.__setattr__(
            self,
            "candidate_overlaps",
            MappingProxyType(
                {str(key): float(value) for key, value in self.candidate_overlaps.items()}
            ),
        )

    def to_dict(self) -> dict[str, object]:
        """Return the JSON-able null-direction record."""
        return {
            "eigenvalue": self.eigenvalue,
            "relative_eigenvalue": self.relative_eigenvalue,
            "direction": list(self.direction),
            "parameter_names": list(PARAMETER_NAMES),
            "dominant_parameters": list(self.dominant_parameters),
            "candidate_overlaps": dict(self.candidate_overlaps),
        }


@dataclass(frozen=True, slots=True)
class IdentifiabilityReport:
    """Eigen-decomposition of the image likelihood Fisher information.

    ``eigenvalues`` are ascending, so ``eigenvalues[0]`` is the worst-measured direction and
    ``eigenvectors[:, 0]`` is that direction.  Nothing here is regularised: a direction the image did
    not measure appears as an eigenvalue at the numerical floor, and it is the caller's declared
    ``eigenvalue_floor`` — not this object — that decides what counts as measured.
    """

    label: str
    fisher: np.ndarray
    eigenvalues: np.ndarray
    eigenvectors: np.ndarray
    candidate_directions: Mapping[str, tuple[float, ...]]

    def __post_init__(self) -> None:
        if not isinstance(self.label, str) or not self.label.strip():
            raise ValueError("label must be a non-empty string")
        object.__setattr__(self, "label", self.label.strip())
        for name in ("fisher", "eigenvectors"):
            matrix = np.asarray(getattr(self, name), dtype=np.float64).copy()
            if matrix.shape != (_N_PARAMETERS, _N_PARAMETERS) or not np.all(np.isfinite(matrix)):
                raise ValueError(
                    f"{name} must be a finite ({_N_PARAMETERS}, {_N_PARAMETERS}) matrix"
                )
            matrix.setflags(write=False)
            object.__setattr__(self, name, matrix)
        values = np.asarray(self.eigenvalues, dtype=np.float64).reshape(-1).copy()
        if values.size != _N_PARAMETERS or not np.all(np.isfinite(values)):
            raise ValueError(f"eigenvalues must be finite with length {_N_PARAMETERS}")
        values.setflags(write=False)
        object.__setattr__(self, "eigenvalues", values)
        object.__setattr__(
            self,
            "candidate_directions",
            MappingProxyType(
                {
                    str(key): tuple(float(entry) for entry in value)
                    for key, value in self.candidate_directions.items()
                }
            ),
        )

    @property
    def largest_eigenvalue(self) -> float:
        """Information along the best-measured direction."""
        return float(self.eigenvalues[-1])

    @property
    def smallest_eigenvalue(self) -> float:
        """Information along the worst-measured direction."""
        return float(self.eigenvalues[0])

    @property
    def condition_number(self) -> float:
        """Ratio of best- to worst-measured information; ``inf`` when the Fisher is exactly singular."""
        smallest = self.smallest_eigenvalue
        if smallest <= 0.0:
            return math.inf
        return self.largest_eigenvalue / smallest

    def directional_information(self, direction: object) -> float:
        """Return ``d^T F d`` for a unit direction ``d``.

        This is the information the image carries about that combination of parameters, and it is the
        quantity a modality contrast compares before and after.

        Args:
            direction: Any length-5 vector; it is normalised internally.

        Returns:
            The Rayleigh quotient of the Fisher matrix along the direction.
        """
        unit = _unit_vector(direction, what="direction")
        return float(unit @ self.fisher @ unit)

    def near_null_directions(self, *, eigenvalue_floor: float) -> tuple[NullDirection, ...]:
        """Return every eigendirection whose eigenvalue is below a caller-declared floor.

        Args:
            eigenvalue_floor: Absolute information below which a direction counts as unmeasured.
                It is required — there is no default, because a default here would be a threshold
                chosen by this module rather than by the contract the caller wrote.

        Returns:
            Ascending tuple of near-null directions, possibly empty.

        Raises:
            ValueError: If the floor is not positive-finite.
        """
        floor = _positive_finite(eigenvalue_floor, what="eigenvalue_floor")
        largest = self.largest_eigenvalue
        found: list[NullDirection] = []
        for index in range(_N_PARAMETERS):
            value = float(self.eigenvalues[index])
            if value >= floor:
                continue
            vector = np.asarray(self.eigenvectors[:, index], dtype=np.float64)
            weights = np.square(vector)
            dominant = tuple(
                PARAMETER_NAMES[position]
                for position in np.argsort(weights)[::-1]
                if weights[position] >= 0.1
            )
            overlaps = {
                name: abs(float(np.asarray(candidate, dtype=np.float64) @ vector))
                for name, candidate in self.candidate_directions.items()
            }
            found.append(
                NullDirection(
                    eigenvalue=max(value, 0.0),
                    relative_eigenvalue=max(value, 0.0) / largest if largest > 0.0 else 0.0,
                    direction=tuple(float(entry) for entry in vector),
                    dominant_parameters=dominant,
                    candidate_overlaps=overlaps,
                )
            )
        return tuple(found)

    def identifiable_fraction(self, parameter: str, *, eigenvalue_floor: float) -> float:
        """Fraction of a parameter's unit vector that lies in the measured subspace.

        The eigenvectors are orthonormal, so ``sum_k V[j, k]^2 == 1``; this returns the part of that
        sum carried by eigenvalues at or above the floor.  A value near zero means the image says
        essentially nothing about that parameter on its own.

        Args:
            parameter: One of :data:`PARAMETER_NAMES`.
            eigenvalue_floor: Caller-declared information floor.

        Returns:
            A number in ``[0, 1]``.
        """
        index = _parameter_index(parameter)
        floor = _positive_finite(eigenvalue_floor, what="eigenvalue_floor")
        measured = self.eigenvalues >= floor
        weights = np.square(np.asarray(self.eigenvectors[index, :], dtype=np.float64))
        return float(np.sum(weights[measured]))

    def to_dict(self, *, eigenvalue_floor: float) -> dict[str, object]:
        """Return the JSON-able identifiability record at a declared floor."""
        return {
            "label": self.label,
            "parameter_names": list(PARAMETER_NAMES),
            "eigenvalues": [float(value) for value in self.eigenvalues],
            "condition_number": self.condition_number,
            "eigenvalue_floor": float(eigenvalue_floor),
            "identifiable_fraction": {
                name: self.identifiable_fraction(name, eigenvalue_floor=eigenvalue_floor)
                for name in PARAMETER_NAMES
            },
            "near_null_directions": [
                direction.to_dict()
                for direction in self.near_null_directions(eigenvalue_floor=eigenvalue_floor)
            ],
            "self_scoring": True,
            "evidence_class": "oracle-only",
        }


def identifiability_report(
    params: InverseParameters,
    scene: ImagingScene,
    design: ObservationDesign,
    *,
    label: str,
    steps: Sequence[float] = JACOBIAN_LOG_STEPS,
) -> IdentifiabilityReport:
    """Build the Fisher eigen-decomposition of one design at one operating point.

    Args:
        params: Operating point.
        scene: Known geometry and calibration.
        design: Which frames are acquired.
        label: Human-readable name recorded in the report.
        steps: Central-difference steps.

    Returns:
        The identifiability report.
    """
    fisher = fisher_information(params, scene, design, steps=steps)
    eigenvalues, eigenvectors = np.linalg.eigh(fisher)
    candidates: dict[str, tuple[float, ...]] = {
        "flux": tuple(float(value) for value in FLUX_DEGENERACY_DIRECTION),
        "analytic-defocus": tuple(
            float(value)
            for value in analytic_defocus_null_direction(params, scene, design.focal_planes_um[0])
        ),
    }
    return IdentifiabilityReport(
        label=label,
        fisher=fisher,
        eigenvalues=eigenvalues,
        eigenvectors=eigenvectors,
        candidate_directions=candidates,
    )


