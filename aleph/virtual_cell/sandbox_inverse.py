# Parameter order of every vector, matrix, and eigenvector in this module.  Four log scales and one
# signed length; see the module docstring for why.
PARAMETER_NAMES: tuple[str, ...] = (
    "log_length_um",
    "log_linear_density",
    "log_psf_sigma_um",
    "log_background_photons",
    "z_um",
)

_N_PARAMETERS = len(PARAMETER_NAMES)

# Central-difference steps in the coordinates above.  These are numerical-differentiation steps, not
# tuned thresholds: for a smooth model the central-difference error is O(h^2) and the round-off floor
# is O(eps/h), so h ~ eps^(1/3) ~ 6e-6 minimises the total.  1e-4 sits above that minimum on purpose
# — it keeps the truncation error at ~1e-8 relative while leaving the round-off floor at ~1e-12, which
# is what makes a genuinely null eigenvalue distinguishable from a merely small one.  Step
# convergence is measured in the test file rather than assumed.
JACOBIAN_LOG_STEPS: tuple[float, ...] = (1e-4, 1e-4, 1e-4, 1e-4, 1e-4)

# The flux-preserving direction the master plan predicts for an unresolved emitter: doubling the
# linear density and halving the length leaves ``density x length`` — hence the photon budget —
# unchanged.  Declared BEFORE any measurement so the measured eigenvector can be scored against it.
FLUX_DEGENERACY_DIRECTION: np.ndarray = np.array(
    [1.0, -1.0, 0.0, 0.0, 0.0], dtype=np.float64
) / math.sqrt(2.0)
FLUX_DEGENERACY_DIRECTION.setflags(write=False)

# Backtracking budget for the MAP iteration.  Twelve halvings shrink a step to 2.4e-4 of itself,
# which is below the convergence tolerance for any step this model produces, so exhausting the budget
# means no decrease exists along the direction and the draw is reported as unconverged.
_LINE_SEARCH_HALVINGS: int = 12


