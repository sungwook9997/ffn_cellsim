def _positive_finite(value: object, *, what: str) -> float:
    if (
        isinstance(value, bool)
        or not isinstance(value, (int, float))
        or not math.isfinite(value)
        or value <= 0.0
    ):
        raise ValueError(f"{what} must be positive-finite")
    return float(value)


def _nonnegative_finite(value: object, *, what: str) -> float:
    if (
        isinstance(value, bool)
        or not isinstance(value, (int, float))
        or not math.isfinite(value)
        or value < 0.0
    ):
        raise ValueError(f"{what} must be finite and nonnegative")
    return float(value)


def _finite(value: object, *, what: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
        raise ValueError(f"{what} must be finite")
    return float(value)


def _positive_int(value: object, *, what: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value < 1:
        raise ValueError(f"{what} must be a positive integer")
    return int(value)


def _parameter_index(name: object) -> int:
    if not isinstance(name, str) or name not in PARAMETER_NAMES:
        raise KeyError(f"unknown parameter {name!r}; expected one of {PARAMETER_NAMES}")
    return PARAMETER_NAMES.index(name)


def _unit_vector(direction: object, *, what: str) -> np.ndarray:
    vector = np.asarray(direction, dtype=np.float64).reshape(-1)
    if vector.size != _N_PARAMETERS or not np.all(np.isfinite(vector)):
        raise ValueError(f"{what} must be a finite vector of length {_N_PARAMETERS}")
    norm = float(np.linalg.norm(vector))
    if norm <= 0.0:
        raise ValueError(f"{what} must have positive norm")
    return vector / norm


