@dataclass(frozen=True, slots=True)
class InverseParameters:
    """The five inferred parameters of one synthetic filament observation.

    ``linear_density`` is photons per micrometre per second, so the emitted photon budget is
    ``linear_density x length_um x exposure_s`` and is invariant to how the segment is subdivided —
    the property that makes the flux degeneracy exactly multiplicative.
    """

    length_um: float
    linear_density: float
    psf_sigma_um: float
    background_photons: float
    z_um: float

    def __post_init__(self) -> None:
        for name in ("length_um", "linear_density", "psf_sigma_um", "background_photons"):
            object.__setattr__(self, name, _positive_finite(getattr(self, name), what=name))
        object.__setattr__(self, "z_um", _finite(self.z_um, what="z_um"))

    def to_vector(self) -> np.ndarray:
        """Return the parameters in the coordinates of :data:`PARAMETER_NAMES`."""
        return np.array(
            [
                math.log(self.length_um),
                math.log(self.linear_density),
                math.log(self.psf_sigma_um),
                math.log(self.background_photons),
                self.z_um,
            ],
            dtype=np.float64,
        )

    @classmethod
    def from_vector(cls, vector: object) -> InverseParameters:
        """Invert :meth:`to_vector`.

        Args:
            vector: Length-5 vector in the coordinates of :data:`PARAMETER_NAMES`.

        Returns:
            The parameter object.

        Raises:
            ValueError: If the vector has the wrong length, is not finite, or exponentiates to a
                non-finite scale.
        """
        values = np.asarray(vector, dtype=np.float64).reshape(-1)
        if values.size != _N_PARAMETERS or not np.all(np.isfinite(values)):
            raise ValueError(f"vector must be finite with length {_N_PARAMETERS}")
        scales = np.exp(values[:4])
        if not np.all(np.isfinite(scales)) or np.any(scales <= 0.0):
            raise ValueError(
                "log-coordinate entry exponentiates to a non-positive or infinite scale"
            )
        return cls(
            length_um=float(scales[0]),
            linear_density=float(scales[1]),
            psf_sigma_um=float(scales[2]),
            background_photons=float(scales[3]),
            z_um=float(values[4]),
        )

    @property
    def total_photons(self) -> float:
        """Photon budget per unit exposure: the quantity the flux degeneracy preserves."""
        return self.length_um * self.linear_density

    def to_dict(self) -> dict[str, float]:
        """Return the JSON-able parameter record in physical units."""
        return {
            "length_um": self.length_um,
            "linear_density_photons_per_um_per_s": self.linear_density,
            "psf_sigma_um": self.psf_sigma_um,
            "background_photons": self.background_photons,
            "z_um": self.z_um,
        }


@dataclass(frozen=True, slots=True)
class ImagingScene:
    """Everything about the observation that is KNOWN and therefore not inferred.

    The emitter centre and orientation are known nuisance geometry: this sandbox asks what an image
    says about the molecular parameters, not about where the object is, and leaving localisation in
    would confound a well-understood degeneracy (position/width) with the ones under test.
    ``read_noise_photons`` and ``saturation_photons`` are camera calibration.
    """

    centre_xy_um: tuple[float, float]
    orientation_rad: float
    height_px: int
    width_px: int
    pixel_size_um: float
    exposure_s: float
    rayleigh_range_um: float
    read_noise_photons: float
    saturation_photons: float = 65535.0
    bit_depth: int = 16
    psf_radius_sigma: float = 4.0
    pixel_quadrature_nodes: int = 4
    point_chain_labels: int = 12

    def __post_init__(self) -> None:
        centre = tuple(self.centre_xy_um)
        if len(centre) != 2:
            raise ValueError("centre_xy_um must be an (x, y) pair")
        object.__setattr__(
            self,
            "centre_xy_um",
            (_finite(centre[0], what="centre_xy_um.x"), _finite(centre[1], what="centre_xy_um.y")),
        )
        object.__setattr__(
            self, "orientation_rad", _finite(self.orientation_rad, what="orientation_rad")
        )
        object.__setattr__(self, "height_px", _positive_int(self.height_px, what="height_px"))
        object.__setattr__(self, "width_px", _positive_int(self.width_px, what="width_px"))
        for name in (
            "pixel_size_um",
            "exposure_s",
            "rayleigh_range_um",
            "saturation_photons",
            "psf_radius_sigma",
        ):
            object.__setattr__(self, name, _positive_finite(getattr(self, name), what=name))
        object.__setattr__(
            self,
            "read_noise_photons",
            _nonnegative_finite(self.read_noise_photons, what="read_noise_photons"),
        )
        if (
            isinstance(self.bit_depth, bool)
            or not isinstance(self.bit_depth, int)
            or not 1 <= self.bit_depth <= 32
        ):
            raise ValueError("bit_depth must be an integer in [1, 32]")
        object.__setattr__(
            self,
            "pixel_quadrature_nodes",
            _positive_int(self.pixel_quadrature_nodes, what="pixel_quadrature_nodes"),
        )
        object.__setattr__(
            self,
            "point_chain_labels",
            _positive_int(self.point_chain_labels, what="point_chain_labels"),
        )
        if self.point_chain_labels < 2:
            raise ValueError("point_chain_labels must be at least two to represent a segment")

    @property
    def camera(self) -> CameraConfig:
        """Lane D's camera model at unit gain, so digital counts ARE photon counts."""
        return CameraConfig(
            photons_per_intensity=1.0,
            read_noise_std_photons=self.read_noise_photons,
            saturation_photons=self.saturation_photons,
            bit_depth=self.bit_depth,
        )

    @property
    def read_variance_photons2(self) -> float:
        """Read-noise variance added to the Poisson variance in the Gaussian likelihood."""
        return self.read_noise_photons * self.read_noise_photons

    def to_dict(self) -> dict[str, object]:
        """Return the JSON-able scene record."""
        return {
            "centre_xy_um": list(self.centre_xy_um),
            "orientation_rad": self.orientation_rad,
            "height_px": self.height_px,
            "width_px": self.width_px,
            "pixel_size_um": self.pixel_size_um,
            "exposure_s": self.exposure_s,
            "rayleigh_range_um": self.rayleigh_range_um,
            "read_noise_photons": self.read_noise_photons,
            "saturation_photons": self.saturation_photons,
            "bit_depth": self.bit_depth,
            "psf_radius_sigma": self.psf_radius_sigma,
            "pixel_quadrature_nodes": self.pixel_quadrature_nodes,
            "point_chain_labels": self.point_chain_labels,
        }

    @property
    def scene_hash(self) -> str:
        """SHA-256 over the canonical scene record."""
        payload = json.dumps(self.to_dict(), sort_keys=True, separators=(",", ":")).encode()
        return hashlib.sha256(payload).hexdigest()


@dataclass(frozen=True, slots=True)
class ObservationDesign:
    """Which frames are acquired — the thing an observation-design failure route gets to change.

    ``focal_planes_um`` lists widefield frames sharing the INFERRED in-focus PSF width, so more planes
    add axial information without adding a new calibration unknown.  ``extra_channel_sigma_um``, when
    given, adds one frame whose lateral width is calibrated INDEPENDENTLY of the inferred ``s0`` — a
    second colour or a higher-resolution channel.  It is what can resolve a segment the widefield
    channel cannot, and therefore what can separate length from density.
    """

    design_id: str
    focal_planes_um: tuple[float, ...]
    extra_channel_sigma_um: float | None = None
    extra_channel_focal_plane_um: float = 0.0
    extra_channel_rayleigh_range_um: float | None = None

    def __post_init__(self) -> None:
        if not isinstance(self.design_id, str) or not self.design_id.strip():
            raise ValueError("design_id must be a non-empty string")
        object.__setattr__(self, "design_id", self.design_id.strip())
        planes = tuple(
            _finite(plane, what="focal_planes_um entry") for plane in self.focal_planes_um
        )
        if not planes:
            raise ValueError("focal_planes_um must contain at least one plane")
        object.__setattr__(self, "focal_planes_um", planes)
        if self.extra_channel_sigma_um is not None:
            object.__setattr__(
                self,
                "extra_channel_sigma_um",
                _positive_finite(self.extra_channel_sigma_um, what="extra_channel_sigma_um"),
            )
        object.__setattr__(
            self,
            "extra_channel_focal_plane_um",
            _finite(self.extra_channel_focal_plane_um, what="extra_channel_focal_plane_um"),
        )
        if self.extra_channel_rayleigh_range_um is not None:
            object.__setattr__(
                self,
                "extra_channel_rayleigh_range_um",
                _positive_finite(
                    self.extra_channel_rayleigh_range_um, what="extra_channel_rayleigh_range_um"
                ),
            )

    @property
    def n_frames(self) -> int:
        """Number of frames the design acquires."""
        return len(self.focal_planes_um) + (0 if self.extra_channel_sigma_um is None else 1)

    def to_dict(self) -> dict[str, object]:
        """Return the JSON-able design record."""
        return {
            "design_id": self.design_id,
            "focal_planes_um": list(self.focal_planes_um),
            "extra_channel_sigma_um": self.extra_channel_sigma_um,
            "extra_channel_focal_plane_um": self.extra_channel_focal_plane_um,
            "extra_channel_rayleigh_range_um": self.extra_channel_rayleigh_range_um,
            "n_frames": self.n_frames,
        }

    @property
    def design_hash(self) -> str:
        """SHA-256 over the canonical design record."""
        payload = json.dumps(self.to_dict(), sort_keys=True, separators=(",", ":")).encode()
        return hashlib.sha256(payload).hexdigest()


@dataclass(frozen=True, slots=True)
class GaussianLogPrior:
    """A proper Gaussian prior in the coordinates of :data:`PARAMETER_NAMES`.

    A proper prior is required, not optional: the likelihood Fisher is singular along the defocus
    direction, so without one the posterior covariance does not exist.  The prior is what makes the
    posterior a distribution; it is emphatically NOT what makes the direction identifiable, which is
    why :class:`IdentifiabilityReport` is built from the likelihood Fisher alone.
    """

    mean: np.ndarray
    sigma: np.ndarray

    def __post_init__(self) -> None:
        for name in ("mean", "sigma"):
            vector = np.asarray(getattr(self, name), dtype=np.float64).reshape(-1).copy()
            if vector.size != _N_PARAMETERS or not np.all(np.isfinite(vector)):
                raise ValueError(f"{name} must be finite with length {_N_PARAMETERS}")
            vector.setflags(write=False)
            object.__setattr__(self, name, vector)
        if np.any(self.sigma <= 0.0):
            raise ValueError("prior sigma must be strictly positive")

    @property
    def precision(self) -> np.ndarray:
        """Diagonal prior precision matrix."""
        matrix = np.diag(1.0 / np.square(self.sigma))
        matrix.setflags(write=False)
        return matrix

    @property
    def mean_parameters(self) -> InverseParameters:
        """The prior mean as physical parameters."""
        return InverseParameters.from_vector(self.mean)

    def draw(self, rng: np.random.Generator) -> np.ndarray:
        """Draw one parameter vector from the prior.

        Args:
            rng: Seeded generator; the seed is recorded by every campaign that calls this.

        Returns:
            A length-5 vector in :data:`PARAMETER_NAMES` coordinates.
        """
        return self.mean + self.sigma * rng.standard_normal(_N_PARAMETERS)

    def to_dict(self) -> dict[str, object]:
        """Return the JSON-able prior record."""
        return {
            "parameter_names": list(PARAMETER_NAMES),
            "mean": [float(value) for value in self.mean],
            "sigma": [float(value) for value in self.sigma],
        }


