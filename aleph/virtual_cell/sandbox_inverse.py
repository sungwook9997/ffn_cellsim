@dataclass(frozen=True, slots=True)
class RendererMismatchReport:
    """How much the closed loop degrades when the truth comes from a different forward model."""

    control_id: str
    matched: CoverageCampaign
    mismatched: CoverageCampaign
    relative_image_residual: float
    coverage_degradation: Mapping[str, float]
    bias_growth_in_sigma: Mapping[str, float]

    def __post_init__(self) -> None:
        object.__setattr__(
            self,
            "coverage_degradation",
            MappingProxyType({str(k): float(v) for k, v in self.coverage_degradation.items()}),
        )
        object.__setattr__(
            self,
            "bias_growth_in_sigma",
            MappingProxyType({str(k): float(v) for k, v in self.bias_growth_in_sigma.items()}),
        )

    @property
    def worst_coverage_degradation(self) -> float:
        """Largest drop in empirical coverage caused by the renderer mismatch."""
        return max(self.coverage_degradation.values())

    @property
    def collapsed_parameters(self) -> tuple[str, ...]:
        """Parameters calibrated under the matched renderer and NOT under the mismatched one."""
        return tuple(
            sorted(
                name
                for name in PARAMETER_NAMES
                if self.matched.per_parameter[name].calibrated
                and not self.mismatched.per_parameter[name].calibrated
            )
        )

    def to_dict(self) -> dict[str, object]:
        """Return the JSON-able mismatch record."""
        return {
            "control_id": self.control_id,
            "matched": self.matched.to_dict(),
            "mismatched": self.mismatched.to_dict(),
            "relative_image_residual": self.relative_image_residual,
            "coverage_degradation": dict(self.coverage_degradation),
            "bias_growth_in_sigma": dict(self.bias_growth_in_sigma),
            "collapsed_parameters": list(self.collapsed_parameters),
            "self_scoring": False,
            "evidence_class": "oracle-only",
        }


def measure_renderer_mismatch(
    scene: ImagingScene,
    design: ObservationDesign,
    prior: GaussianLogPrior,
    *,
    control_id: str,
    n_draws: int,
    nominal_level: float,
    seed: int,
    truth_family: RendererFamily = RendererFamily.ALIASED_POINT_CHAIN,
    rayleigh_scale: float = 1.0,
    max_refinement_steps: int = 16,
    trust_radius_prior_sigma: float = 6.0,
    steps: Sequence[float] = JACOBIAN_LOG_STEPS,
) -> RendererMismatchReport:
    """Run the same campaign twice, once with the matched renderer and once with a different one.

    This is the only defence this module offers against master-plan A6.  A closed loop scored inside
    one renderer family is worth exactly the amount by which it survives leaving that family, and
    that amount is measured here rather than asserted.

    Args:
        scene: Known geometry and calibration.
        design: Which frames are acquired.
        prior: Generative and inference prior.
        control_id: Name of the control.
        n_draws: Ensemble size for BOTH campaigns.
        nominal_level: Claimed central probability.
        seed: Recorded seed; both campaigns use it, so the truth draws are paired.
        truth_family: Renderer family used to generate the mismatched truths.
        rayleigh_scale: Axial mis-calibration applied to the mismatched truths only.
        max_refinement_steps: Iteration ceiling passed to both campaigns.
        trust_radius_prior_sigma: Iterate box passed to both campaigns.
        steps: Central-difference steps.

    Returns:
        The mismatch report.
    """
    if not isinstance(control_id, str) or not control_id.strip():
        raise ValueError("control_id must be a non-empty string")
    matched = run_coverage_campaign(
        scene,
        design,
        prior,
        n_draws=n_draws,
        nominal_level=nominal_level,
        seed=seed,
        label=f"{control_id}:matched",
        truth_family=RendererFamily.PIXEL_INTEGRATED_LINE,
        rayleigh_scale=1.0,
        max_refinement_steps=max_refinement_steps,
        trust_radius_prior_sigma=trust_radius_prior_sigma,
        steps=steps,
    )
    mismatched = run_coverage_campaign(
        scene,
        design,
        prior,
        n_draws=n_draws,
        nominal_level=nominal_level,
        seed=seed,
        label=f"{control_id}:mismatched",
        truth_family=truth_family,
        rayleigh_scale=rayleigh_scale,
        max_refinement_steps=max_refinement_steps,
        trust_radius_prior_sigma=trust_radius_prior_sigma,
        steps=steps,
    )
    reference = prior.mean_parameters
    matched_image = expected_photons(reference, scene, design)
    mismatched_image = expected_photons(
        reference, scene, design, family=truth_family, rayleigh_scale=rayleigh_scale
    )
    background = reference.background_photons
    signal_norm = float(np.linalg.norm(matched_image - background))
    residual = float(np.linalg.norm(mismatched_image - matched_image))
    degradation = {
        name: matched.per_parameter[name].empirical_coverage
        - mismatched.per_parameter[name].empirical_coverage
        for name in PARAMETER_NAMES
    }
    bias_growth = {
        name: abs(mismatched.mean_bias_in_sigma[name]) - abs(matched.mean_bias_in_sigma[name])
        for name in PARAMETER_NAMES
    }
    return RendererMismatchReport(
        control_id=control_id.strip(),
        matched=matched,
        mismatched=mismatched,
        relative_image_residual=residual / signal_norm if signal_norm > 0.0 else math.inf,
        coverage_degradation=degradation,
        bias_growth_in_sigma=bias_growth,
    )


