"""Cross-cutting contracts and CPU oracles for the probabilistic virtual-cell programme.

This package does not own simulation physics.  ``aleph.ac`` remains the explicit accepted-step
reference runtime; the modules here describe broader cell-state manifests, representation/evidence
provenance, sandbox experiments, and small deterministic oracles that can be validated without a GPU.

Nothing exported here may be promoted to native evidence.  Every verdict this package produces is an
UNVERIFIED OBSERVER: it can refuse, and it can measure its own approximation error, but it cannot
adjudicate a PI-gated predicate and cannot declare ``NATIVE_ACCEPTED``.

ONE NAME IS DELIBERATELY NOT RE-EXPORTED.  ``sweep`` and ``surrogate`` each define an
``ExpansionRoute`` enum, and they are DIFFERENT types with only partly overlapping members
(``adaptive-design`` and ``model-inadequacy`` appear in both; ``regime-partition`` and
``native-evaluation`` in one each).  Exporting a bare ``ExpansionRoute`` would silently resolve to
whichever module was imported last, which is exactly the class of defect this package exists to
catch, so both are exported under qualified names instead.  Unifying them is a cross-lane design
change and is left as one -- a merged enum is not something an integration step should invent.

A SECOND NAME IS ALSO NOT RE-EXPORTED BARE.  Three sandbox modules each define
``EVIDENCE_AUTHORITY``, and the three values are NOT the same kind of thing: two are the
authority label ``"unverified-observer"`` while the third is a prose sentence describing what the
module's results may not be used for.  One package-level name covering both would be a lie about
what a caller is reading, so each is exported under its own module-qualified alias.  Reconciling
the three into one vocabulary is a cross-lane change and is left as one.
"""

