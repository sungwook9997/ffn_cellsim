"""H.LINC nesprin-SUN bridge ACTIVATION GATE (LIVE, 2026-06-09).

Fourth compartment graduated EXPERIMENTAL->LIVE under the PI ownership grant.
LINC (Option A) bonds each ``nucleus_bead`` to its nearest perinuclear
``if_bead`` (the LIVE intermediate-filament cage) with a per-bond EXACT-r0
harmonic, so the nucleus is mechanically coupled to the perinuclear cytoskeleton
at the physiological operating point. The gate builds the FULL physiological
baseline cell with the IF cage ON, OFF vs ON for LINC, and checks the
build-time activation controls:

  BRIDGES FORMED  — ON forms n_bridges>0 linc_nesprin bonds (REFUTE-guard against
                    the zero-bonds-at-real-geometry trap). LINC adds ZERO
                    particles (bonds only) → particle count IDENTICAL OFF vs ON.
  FORCE-FREE      — each bridge is born at its EXACT as-built nucleus↔if_bead
                    separation → construction strain ~0 (the ~8 pN resting
                    tension is generated by actomyosin AFTER equilibration, not
                    injected at build; physiological-baseline rule).
  NO-CONTAM       — cortical γ_soft IDENTICAL OFF vs ON (linc_ bonds registry-
                    denylisted); every linc_ bond type excluded from the mask.
  OFF-IDENTITY    — LINC off reproduces the IF-cage baseline inventory exactly.
  CFL HEADROOM    — production dt ≤ linc_cfl_dt_max(k_linc, γ_bead) (analytic).

PRIMARY <T_linc> ∈ [2,10] pN resting-tension oracle (Déjardin 2020) needs an
equilibrated actomyosin run and is DEFERRED (the full-cell raw run trips the
BAOAB guard — needs the equilibration prelude, the same known full-cell issue
as the other compartments). k_linc=1e-2 N/m is the route-A folded-rod secant
(Rief 1999; ORDER, PI-pending ratification). ⚠ At the ×40 mesoscale the
nucleus↔if_bead separation is ~0.5-1.5 µm (NOT the 50 nm real nesprin span), so
r0 is an EFFECTIVE mesoscale coupling length — see PLATFORM_PI_QUEUE.

Run:  python ffn_sim/scripts/h7_linc_activation_gate.py
"""

from __future__ import annotations

import sys
from pathlib import Path

_HERE = Path(__file__).resolve()
if str(_HERE.parents[2]) not in sys.path:
    sys.path.insert(0, str(_HERE.parents[2]))

