"""Ventral stress fibers — explicit contractile actomyosin bundles (KU-3.5/3.1).

ADDITIVE, DEFAULT-OFF compartment. A ventral stress fiber (vSF) is a
contractile actomyosin BUNDLE that spans focal-adhesion to focal-adhesion
along the basal (ventral) plane of an adherent cell. This module lays out
``n_SF`` such bundles as EXPLICIT particle/bond topology — there is NO lumped
"cable spring" standing in for the fiber. Each bundle is built from the SAME
fine-grained vocabulary the cortex already uses:

* an explicit chain of actin beads (``sf_actin``) along the FA→FA axis,
* explicit α-actinin crosslinker head-pairs (``sf_xlink_head``) laid down at
  a SARCOMERIC periodicity (Tojkander 2012; Hotulainen-Lappalainen 2006),
* explicit NMII bipolar minifilaments (Stam-Hocky D5 architecture, reused
  verbatim from :mod:`ffn_sim.cortex.myosin` / :mod:`ffn_sim.bridge.motor`)
  that LOAD the bundle — the contractile force is generated by explicit motor
  heads pulling on explicit actin, not by a prescribed tension.

The two endpoints of every bundle anchor onto EXISTING focal-adhesion clutch
particles (the ``integrin``/clutch beads built by :mod:`ffn_sim.bridge.fa`),
so the SF tension is transmitted into the substrate through the real FA load
path. This compartment therefore REQUIRES the ``fa`` compartment to be present
(endpoint FA-clutch tags are passed in by the Lead at wiring time).

Why this is a BASAL-PLANE observable, NOT cortical hoop γ
---------------------------------------------------------
The SF bundle carries a NON-CORTICAL, FA-to-FA load path. Its bonds are
chord-like (they cut straight across the basal plane between two adhesions),
they are NOT part of the cortical shell whose hoop stress defines the
cortical tension γ (KU-3.5). Every bond type this module creates is prefixed
``sf_`` (see :data:`GAMMA_DENYLIST_PREFIX`) so the cortical-tension estimator
(:mod:`ffn_sim.cortex.cortical_tension`) can DENYLIST it and never sum SF
tension into γ. SF contractility is reported as its own basal observable —
:func:`measure_sf_tension` returns the mean axial tension of the explicit
``sf_actin`` chain bonds, comparable to the single-SF force band below.

Explicit mechanism — what particles / bonds
-------------------------------------------
Per bundle ``b`` spanning FA endpoint ``A`` → FA endpoint ``B``:

* ``n_beads`` ``sf_actin`` beads evenly spaced on the segment A→B
  (bead spacing ``ℓ0_actin = |B−A| / (n_beads−1)``).
* ``n_beads − 1`` ``sf_actin_bond`` harmonic bonds along the chain
  (the load-bearing backbone; tension measured here).
* the two end beads carry an ``sf_anchor`` harmonic bond each, tying bead 0
  to FA endpoint ``A`` and bead ``n_beads−1`` to FA endpoint ``B``.
* α-actinin crosslinkers laid down every ``sarcomere_spacing`` along the
  bundle: an ``sf_xlink_head`` pair joined by an ``sf_xlink_intra`` bond,
  with each head tied to the nearest ``sf_actin`` bead by an ``sf_xlink_attach``
  bond (sarcomeric banding; one crosslinker per period).
* NMII minifilaments (D5 Stam-Hocky): backbone + head beads + intra bonds,
  reused from :mod:`ffn_sim.cortex.myosin`. These are appended through the
  EXISTING myosin builder so the head↔actin stepping (D6 Hill) and Bell-Evans
  D2 kinetics carry over unchanged — the myosin is the explicit force source.
  (The myosin block is OPTIONAL at this layer: this module builds the actin +
  α-actinin scaffold and the FA anchors; the Lead attaches the existing
  cortex/bridge myosin updater onto the ``sf_actin`` chain. When myosin is not
  attached the bundle is a passive elastic cable — still explicit, no lumped
  tension is injected. A ``sf_`` myosin variant is a documented TODO so the SF
  motors are denylisted distinctly from cortical motors.)

Sanity Gate
-----------
*Per CLAUDE.md Hard Rule. STATIC + analytical checks in
``ffn_sim/tests/test_stress_fibers.py``.*

1. **Dimensional analysis**
   - ``k_actin`` [N/m] · ``Δℓ`` [m] → axial tension [N]. ✓
   - ``sarcomere_spacing`` [m]; ``n_sarcomeres = round(L_bundle / spacing)``
     dimensionless. ✓
   - ``ℓ0_actin = L_bundle / (n_beads − 1)`` [m]. ✓
   - ``k_anchor`` [N/m] · anchor stretch [m] → anchor force [N]. ✓
   - Single-SF tension band ``F_SF`` [N] = ``Σ`` axial bond tensions / chain.

2. **Boundary cases**
   - ``enabled=False`` (or cfg missing / ``enabled: false``): resolver returns
     ``ResolvedStressFibers(enabled=False, ...)`` with zeros; the builder
     EARLY-RETURNS its input snapshot unchanged (0 particles, 0 bonds added).
   - ``n_SF = 0``: builder is a no-op (empty layout).
   - ``n_beads < 2``: ValueError (a bundle needs ≥ 2 beads to span A→B).
   - ``L_bundle = |B − A| = 0`` (coincident FA endpoints): ValueError at
     LAYOUT time (degenerate bundle — no axis).
   - any non-finite / ≤ 0 stiffness / spacing: ValueError at resolve time.

3. **Conservation invariants / no-net-force**
   - The ``sf_actin_bond`` and ``sf_xlink_*`` bonds are ``md.bond.Harmonic``
     pairs → Newton's 3rd law holds → the bundle injects ZERO net momentum
     internally. The ``sf_anchor`` bond is also a symmetric harmonic pair
     between bead and FA particle (no external field), so the FA↔SF coupling
     is momentum-conserving too. (Contrast ERM, which is an external radial
     field and intentionally breaks translation symmetry.)
   - Particle count added = ``Σ_b [ n_beads_b + 2·n_sarcomeres_b ]``.
   - Bond count added = ``Σ_b [ (n_beads_b − 1)  (chain)
     + 2  (two FA anchors)
     + n_sarcomeres_b·2  (xlink: 1 intra + ... )]`` — exact count asserted in
     the test (see :meth:`StressFiberLayout` docstring for the breakdown).

4. **Numerical sanity (CFL)**
   - The actin backbone stiffness ``k_actin`` sets ``τ_actin = γ_b / k_actin``.
     With ``k_actin = 1e-2 N/m`` (see Magic-Number Block) and the cortex
     per-bead drag ``γ_b ≈ 3.9e-10 N·s/m``, ``τ_actin ≈ 3.9e-8 s = 39 ns`` —
     comparable to the cortex ``dt_CFL ≈ 13 ns``, so the SF backbone is the
     stiffest element and SETS the step. :func:`stress_fiber_dt_cfl` returns
     ``cfl_safety · γ_b / k_stiffest`` so the Lead can gate ``dt`` against it
     (the anchor ``k_anchor`` is comparable; ``k_xl`` is far softer). A
     ``cfl_strict`` gate is provided in the attach helper, mirroring ERM.
   - All positions / forces float64.

5. **Sign / sense**
   - A ``sf_actin_bond`` stretched beyond its rest length ``ℓ0_actin`` pulls
     its two beads TOGETHER (toward each other / inward along the bundle axis)
     — contractile. STATIC test stretches one chain bond and asserts the force
     on the outer bead points back toward its neighbour.
   - An ``sf_anchor`` bond stretched pulls the SF end bead TOWARD its FA
     anchor (the FA transmits the pull into the substrate). STATIC test.

6. **Measurement-protocol consistency**
   - :func:`measure_sf_tension` reports the mean axial chain-bond tension
     ``T = k_actin · max(0, |Δr| − ℓ0_actin)`` over the ``sf_actin_bond``
     family of one bundle — the SAME quantity the single-SF force band probes
     (Kumar 2006 ablation tension ~10-30 nN). It is a BASAL observable, summed
     over the ``sf_`` load path, and is explicitly DENYLISTED from γ.

Compartment Performance Contract
--------------------------------
* **Particle types added**: ``sf_actin`` (backbone beads), ``sf_xlink_head``
  (α-actinin heads). (NMII reuses the existing ``cortex_myosin_*`` types via
  the shared builder; no new myosin particle type is minted here.)
* **Particle count** at ``n_SF`` bundles, ``n_beads`` per bundle,
  ``n_sarc`` α-actinin periods per bundle:
  ``n_SF · (n_beads + 2·n_sarc)``. For a representative basal layout
  (``n_SF = 20``, ``n_beads = 24`` → ~12 µm bundle at 0.5 µm spacing,
  ``n_sarc ≈ 24``): ``20·(24 + 48) = 1440`` particles — well under the ~1000
  mesoscopic cortex filaments and a small fraction of native ~38000.
  At native scale (``n_SF ≈ 50``, ``n_beads ≈ 50``, ``n_sarc ≈ 50``):
  ``50·(50 + 100) = 7500`` particles. SF is a SPARSE basal compartment.
* **Bond / angle count**: per bundle ``(n_beads − 1) + 2 + 2·n_sarc``
  harmonic bonds; NO angles (the bundle is a straight FA→FA chord; bending
  rigidity is a documented TODO). At ``n_SF=20`` above: ``20·(23+2+48)=1460``
  bonds.
* **Per-step force**: NO. This module adds bonds only; force is the standard
  ``md.bond.Harmonic`` already in the integrator (the SF contraction is driven
  by the reused myosin updater, which is per-BATCH, not per-step).
* **Per-batch updater**: only via the REUSED cortex/bridge myosin
  ``MyosinStepUpdater`` (D2 Bell-Evans + D6 Hill) when the Lead attaches it to
  the ``sf_actin`` chain. This module itself adds NO new updater.
* **uses cpu_local_snapshot**: NO (builder works on a gsd/HOOMD snapshot;
  the reused myosin updater uses ``get_snapshot``, same as cortex).
* **uses cKDTree / broad-phase**: NO at construction (α-actinin is placed by
  arithmetic along the known bundle axis). The reused myosin binder uses a
  KDTree as it already does in cortex — unchanged.
* **hot-path priority**: P2 (sparse basal compartment; far fewer particles
  than cortex; not in the per-step force loop).
* **GPU path now**: builtin (``md.bond.Harmonic`` is GPU-resident in HOOMD;
  the reused myosin updater follows the cortex GPU-main port plan).
* **native ForceCompute candidate**: NO — no custom per-step force is added;
  the only custom kernel involved is the shared myosin stepper.
* **bottleneck risk**: LOW. The SF compartment is small; the cost is in the
  shared myosin updater (already profiled for cortex), not here.

References
----------
- Sarcomeric α-actinin periodicity ~0.5-1 µm in non-muscle ventral stress
  fibers: Tojkander, Gateva & Lappalainen 2012, J Cell Sci 125:1855-1864
  ("Actin stress fibers — assembly, dynamics and biological roles");
  Hotulainen & Lappalainen 2006, J Cell Biol 173:383-394 (vSF arise from
  dorsal SF + transverse arcs; periodic α-actinin/myosin banding).
- Single ventral stress fiber contractile tension ~10-30 nN: Kumar, Maxwell,
  Heisterkamp, Polte, Lele, Salanga, Mazur & Ingber 2006, Biophys J
  90:3762-3773 (single-living-SF laser ablation, Kelvin-Voigt retraction).
- Traction stress ~5.5 nN/µm² at FA: Balaban et al. 2001, Nat Cell Biol
  3:466-472 (force on substrate at focal adhesions).
- NMII bipolar minifilament (D5) + Hill F-V (D6): Stam et al. 2017 PNAS;
  Hill 1938; Kovács 2003 — reused via :mod:`ffn_sim.cortex.myosin` /
  :mod:`ffn_sim.bridge.motor`.
- α-actinin slip-bond rates: Ferrer 2008 PNAS (k_off0 0.066 /s) — reused via
  :mod:`ffn_sim.cortex.crosslinkers` when the Lead wires SF crosslinker kinetics.
- Builder/resolve/Sanity-Gate pattern: :mod:`ffn_sim.cortex.erm`,
  :mod:`ffn_sim.cell.nucleus`, :mod:`ffn_sim.cortex.crosslinkers`.
"""

