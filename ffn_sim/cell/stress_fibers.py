@dataclass(frozen=True, slots=True)
class ResolvedStressFibers:
    """Resolved ventral-stress-fiber parameters (SI units).

    All lengths in metres, stiffnesses in N/m, forces in N. A disabled
    compartment carries ``enabled=False`` and zeros so the builder no-ops.
    """

    enabled: bool

    n_SF: int                       # number of ventral stress-fiber bundles
    n_beads_per_SF: int             # explicit sf_actin beads along each bundle
    sarcomere_spacing: float        # m   α-actinin banding period (0.5-1 µm)

    # Stiffnesses (SI: N/m)
    k_actin: float | None           # N/m  sf_actin backbone bond stiffness (PI)
    k_anchor: float | None          # N/m  sf_anchor SF→FA bond stiffness (PI)
    k_xl: float                     # N/m  α-actinin intra/attach stiffness
    alpha_length: float             # m    α-actinin head-to-head rest length

    # Single-SF tension band (Kumar 2006) — VALIDATION band, not a force input.
    sf_tension_band_N: tuple[float, float]  # N   (10 nN, 30 nN)

    seed: int

    # Derived (filled by resolve_stress_fibers)
    n_xl_per_SF_hint: int = 0       # informational: sarcomeres per ~typical bundle
    extras: dict[str, Any] = field(default_factory=dict)


def _require_finite_positive(name: str, x: float) -> None:
    if not (math.isfinite(x) and x > 0.0):
        raise ValueError(f"{name} must be finite and > 0; got {x!r}")


def resolve_stress_fibers(
    cfg: dict,
    *,
    kT: float = 4.28e-21,
    R_cell: float | None = None,
    dt: float | None = None,
) -> ResolvedStressFibers:
    """Resolve the ``stress_fibers`` config block (DEFAULT-OFF).

    Args:
        cfg: The ``stress_fibers`` sub-dict, OR a parent dict that contains a
            ``stress_fibers`` key. When the block is missing, or contains
            ``enabled: false``, a disabled :class:`ResolvedStressFibers` is
            returned (all builders then no-op).
        kT: Thermal energy [J]; accepted for signature symmetry with the other
            resolvers (not used to set any SF constant — none are thermal).
        R_cell: Cell radius [m] — accepted for context; not required here.
        dt: Host timestep [s] — accepted for context (CFL gating is done by the
            attach helper, which has the per-bead drag in hand).

    Returns:
        A frozen :class:`ResolvedStressFibers`.

    Raises:
        ValueError: on negative / zero / non-finite parameters when ENABLED.
    """
    # Unwrap a parent config.
    if isinstance(cfg, dict) and "stress_fibers" in cfg:
        cfg = cfg["stress_fibers"]
    if cfg is None:
        cfg = {}

    enabled = bool(cfg.get("enabled", False))

    if not enabled:
        # OFF-identity: zeros, no PI-required field forced.
        return ResolvedStressFibers(
            enabled=False,
            n_SF=0,
            n_beads_per_SF=0,
            sarcomere_spacing=0.0,
            k_actin=None,
            k_anchor=None,
            k_xl=0.0,
            alpha_length=0.0,
            sf_tension_band_N=(0.0, 0.0),
            seed=int(cfg.get("seed", 47)),
        )

    n_SF = int(cfg.get("n_SF", 0))
    n_beads_per_SF = int(cfg.get("n_beads_per_SF", 24))
    # Sarcomeric α-actinin periodicity: 0.5-1 µm (Tojkander 2012 JCS;
    # Hotulainen-Lappalainen 2006 JCB). Default 0.5 µm (lower band — the
    # tighter banding seen in non-muscle ventral SFs).
    sarcomere_spacing = float(cfg.get("sarcomere_spacing", 0.5e-6))

    # k_actin / k_anchor: PI-flagged (no fine-grained mesoscale anchor yet).
    # Read from cfg if the PI has set them; otherwise carry the documented
    # default ORDER (Kumar 2006 ~10-30 nN over a ~µm strain → ~1e-2 N/m).
    k_actin = cfg.get("k_actin", 1.0e-2)
    k_actin = None if k_actin is None else float(k_actin)
    k_anchor = cfg.get("k_anchor", k_actin)
    k_anchor = None if k_anchor is None else float(k_anchor)

    # α-actinin crosslinker (reuse KU-3.19 vocabulary):
    #   k_xl   = 0.1 pN/µm = 1e-7 N/m  (Furuike 2001 / Ferrer 2008; same as
    #            cortex/crosslinkers.py k_intra default).
    #   alpha_length = 35 nm  (α-actinin head-to-head, KU-3.19).
    k_xl = float(cfg.get("k_xl", 1.0e-7))
    alpha_length = float(cfg.get("alpha_length", 35.0e-9))

    # Single-SF tension validation band (Kumar 2006 Biophys J 90:3762): ~10-30 nN.
    band = cfg.get("sf_tension_band_N", (10.0e-9, 30.0e-9))
    sf_tension_band_N = (float(band[0]), float(band[1]))

    seed = int(cfg.get("seed", 47))

    # ---- §2 boundary checks (ENABLED path) ----
    if n_SF < 0:
        raise ValueError(f"n_SF must be ≥ 0; got {n_SF}")
    if n_beads_per_SF < 2:
        raise ValueError(
            f"n_beads_per_SF must be ≥ 2 (a bundle spans FA→FA); "
            f"got {n_beads_per_SF}"
        )
    _require_finite_positive("sarcomere_spacing", sarcomere_spacing)
    _require_finite_positive("k_xl", k_xl)
    _require_finite_positive("alpha_length", alpha_length)
    if not (sf_tension_band_N[0] >= 0.0 and sf_tension_band_N[1] > sf_tension_band_N[0]):
        raise ValueError(
            f"sf_tension_band_N must be a positive ordered (lo, hi); "
            f"got {sf_tension_band_N}"
        )
    # k_actin / k_anchor may be None (PI-flagged disabled), else finite-positive.
    if k_actin is not None:
        _require_finite_positive("k_actin", k_actin)
    if k_anchor is not None:
        _require_finite_positive("k_anchor", k_anchor)

    # Informational hint: sarcomeres per a "typical" bundle of n_beads.
    # (Actual per-bundle count is geometry-dependent and computed at layout.)
    n_xl_hint = 0

    return ResolvedStressFibers(
        enabled=True,
        n_SF=n_SF,
        n_beads_per_SF=n_beads_per_SF,
        sarcomere_spacing=sarcomere_spacing,
        k_actin=k_actin,
        k_anchor=k_anchor,
        k_xl=k_xl,
        alpha_length=alpha_length,
        sf_tension_band_N=sf_tension_band_N,
        seed=seed,
        n_xl_per_SF_hint=n_xl_hint,
        extras={
            "kT": float(kT),
            "R_cell": (None if R_cell is None else float(R_cell)),
            "dt": (None if dt is None else float(dt)),
        },
    )


def stress_fiber_dt_cfl(
    p: ResolvedStressFibers, *, gamma_b: float, cfl_safety_factor: float = 0.1
) -> float:
    """Return the SF-stiffest-element CFL timestep ``cfl_safety · γ_b / k``.

    The stiffest SF element sets the step: ``k = max(k_actin, k_anchor)``.
    Mirrors the ERM CFL convention (D3 BAOAB).

    Raises:
        NotImplementedError: if ``k_actin`` is PI-flagged (None) — the CFL
            cannot be computed without the (PI-pending) backbone stiffness.
    """
    if p.k_actin is None:
        raise NotImplementedError(
            "stress_fiber_dt_cfl needs k_actin, which is PI-flagged None "
            "(see PI_DECISIONS). Set stress_fibers.k_actin to a ratified value."
        )
    k_anchor = p.k_anchor if p.k_anchor is not None else p.k_actin
    k_stiffest = max(p.k_actin, k_anchor)
    return cfl_safety_factor * gamma_b / k_stiffest


