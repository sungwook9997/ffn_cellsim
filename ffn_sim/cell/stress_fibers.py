@dataclass(slots=True)
class StressFiberLayout:
    """Per-bundle construction bookkeeping (tags + positions).

    Particle-block layout (appended after the existing ``n_part_old`` tags):
    for bundle ``b`` the block is ``[ sf_actin × n_beads_b ,
    sf_xlink_head × (2·n_sarc_b) ]``.

    Bond breakdown per bundle (all ``sf_``-prefixed):
      * ``n_beads_b − 1``   ``sf_actin_bond``     (backbone chain)
      * ``2``               ``sf_anchor``         (bead0↔FA_A, beadEnd↔FA_B)
      * ``n_sarc_b``        ``sf_xlink_intra``    (one per α-actinin period)
      * ``2·n_sarc_b``      ``sf_xlink_attach``   (each head → nearest bead)

    Attributes:
        actin_tags: list of (n_beads_b,) int arrays — global sf_actin bead tags.
        xlink_head_tags: list of (2·n_sarc_b,) int arrays — α-actinin head tags.
        actin_positions: list of (n_beads_b, 3) float64 bead positions.
        xlink_head_positions: list of (2·n_sarc_b, 3) float64 head positions.
        fa_endpoints: (n_SF, 2) int — the (FA_A_tag, FA_B_tag) per bundle.
        n_sarc: (n_SF,) int — α-actinin periods realised per bundle.
        ell0_actin: (n_SF,) float — backbone bead spacing per bundle.
        particle_tag_start: int — first appended particle tag.
    """

    actin_tags: list[np.ndarray]
    xlink_head_tags: list[np.ndarray]
    actin_positions: list[np.ndarray]
    xlink_head_positions: list[np.ndarray]
    fa_endpoints: np.ndarray
    n_sarc: np.ndarray
    ell0_actin: np.ndarray
    particle_tag_start: int


def generate_stress_fiber_layout(
    p: ResolvedStressFibers,
    fa_endpoint_positions: np.ndarray,
    fa_endpoint_tags: np.ndarray,
    *,
    particle_tag_start: int,
    rng: np.random.Generator | None = None,
) -> StressFiberLayout:
    """Lay out ``n_SF`` bundles between pairs of FA endpoint positions.

    Args:
        p: Resolved SF parameters (must be ``enabled``; a disabled ``p`` yields
            an empty layout).
        fa_endpoint_positions: (M, 3) float64 — positions of candidate FA clutch
            anchor particles (basal plane). ``M ≥ 2·n_SF`` is required so each
            bundle gets two DISTINCT endpoints.
        fa_endpoint_tags: (M,) int — global particle tags of those FA anchors
            (the ``sf_anchor`` bond ties an SF end bead to this tag).
        particle_tag_start: Global tag where the first appended SF particle sits
            (typically the current ``snap.particles.N``).
        rng: Optional RNG (default seeded from ``p.seed``).

    Returns:
        A :class:`StressFiberLayout`.

    Raises:
        ValueError: if too few FA endpoints, or a degenerate (zero-length)
            bundle would result.
    """
    if rng is None:
        rng = np.random.default_rng(p.seed)

    pos = np.asarray(fa_endpoint_positions, dtype=np.float64).reshape(-1, 3)
    tags = np.asarray(fa_endpoint_tags, dtype=np.int64).reshape(-1)
    if pos.shape[0] != tags.shape[0]:
        raise ValueError(
            "fa_endpoint_positions and fa_endpoint_tags length mismatch "
            f"({pos.shape[0]} vs {tags.shape[0]})."
        )

    if (not p.enabled) or p.n_SF == 0:
        return StressFiberLayout(
            actin_tags=[],
            xlink_head_tags=[],
            actin_positions=[],
            xlink_head_positions=[],
            fa_endpoints=np.empty((0, 2), dtype=np.int64),
            n_sarc=np.empty((0,), dtype=np.int64),
            ell0_actin=np.empty((0,), dtype=np.float64),
            particle_tag_start=particle_tag_start,
        )

    M = pos.shape[0]
    if M < 2 * p.n_SF:
        raise ValueError(
            f"need ≥ 2·n_SF = {2 * p.n_SF} FA endpoints to span {p.n_SF} "
            f"bundles with distinct ends; got {M}."
        )

    # Pair FA endpoints without reuse: shuffle, take consecutive pairs.
    order = rng.permutation(M)
    endpoint_pairs = order[: 2 * p.n_SF].reshape(p.n_SF, 2)

    actin_tags: list[np.ndarray] = []
    xlink_head_tags: list[np.ndarray] = []
    actin_positions: list[np.ndarray] = []
    xlink_head_positions: list[np.ndarray] = []
    fa_endpoints = np.empty((p.n_SF, 2), dtype=np.int64)
    n_sarc_arr = np.empty((p.n_SF,), dtype=np.int64)
    ell0_arr = np.empty((p.n_SF,), dtype=np.float64)

    next_tag = int(particle_tag_start)
    nb = p.n_beads_per_SF

    for b in range(p.n_SF):
        ia, ib = int(endpoint_pairs[b, 0]), int(endpoint_pairs[b, 1])
        A = pos[ia]
        B = pos[ib]
        fa_endpoints[b] = (int(tags[ia]), int(tags[ib]))

        axis = B - A
        L = float(np.linalg.norm(axis))
        if not (math.isfinite(L) and L > 0.0):
            raise ValueError(
                f"degenerate bundle {b}: FA endpoints coincide (|B−A| = {L})."
            )
        u = axis / L
        ell0 = L / (nb - 1)
        ell0_arr[b] = ell0

        # Backbone beads evenly along A→B.
        ts = np.linspace(0.0, 1.0, nb)
        beads = A[None, :] + ts[:, None] * axis[None, :]
        bead_tags = np.arange(next_tag, next_tag + nb, dtype=np.int64)
        next_tag += nb
        actin_positions.append(beads)
        actin_tags.append(bead_tags)

        # α-actinin sarcomeric banding: one crosslinker every sarcomere_spacing.
        # n_sarc = number of WHOLE periods that fit along the bundle length.
        n_sarc = int(max(1, round(L / p.sarcomere_spacing)))
        # Cap so heads always have a backbone bead nearby (≤ n_beads−1 periods).
        n_sarc = int(min(n_sarc, nb - 1))
        n_sarc_arr[b] = n_sarc

        # Band positions along the bundle (centres of each period).
        band_s = (np.arange(n_sarc) + 0.5) / n_sarc          # ∈ (0,1)
        band_pts = A[None, :] + band_s[:, None] * axis[None, :]
        # Lateral offset for the two α-actinin heads (perpendicular to axis),
        # half the rest length to each side so the intra bond is force-free.
        # Build any unit vector ⟂ u.
        ref = np.array([1.0, 0.0, 0.0]) if abs(u[0]) < 0.9 else np.array([0.0, 1.0, 0.0])
        perp = np.cross(u, ref)
        perp = perp / max(float(np.linalg.norm(perp)), 1e-30)
        half = 0.5 * p.alpha_length
        heads = np.empty((2 * n_sarc, 3), dtype=np.float64)
        heads[0::2] = band_pts - half * perp[None, :]
        heads[1::2] = band_pts + half * perp[None, :]
        head_tags = np.arange(next_tag, next_tag + 2 * n_sarc, dtype=np.int64)
        next_tag += 2 * n_sarc
        xlink_head_positions.append(heads)
        xlink_head_tags.append(head_tags)

    return StressFiberLayout(
        actin_tags=actin_tags,
        xlink_head_tags=xlink_head_tags,
        actin_positions=actin_positions,
        xlink_head_positions=xlink_head_positions,
        fa_endpoints=fa_endpoints,
        n_sarc=n_sarc_arr,
        ell0_actin=ell0_arr,
        particle_tag_start=particle_tag_start,
    )


# ===========================================================================
# Snapshot-extension builder
# ===========================================================================
def extend_snapshot_with_stress_fibers(
    base_snap,
    p: ResolvedStressFibers,
    fa_endpoint_positions: np.ndarray | None = None,
    fa_endpoint_tags: np.ndarray | None = None,
    *,
    rng: np.random.Generator | None = None,
):
    """Append explicit SF particles + bonds onto a gsd/HOOMD snapshot.

    DEFAULT-OFF: when ``p.enabled`` is False (or ``p.n_SF == 0``) this is a
    NO-OP and returns ``base_snap`` UNCHANGED (same object), adding zero
    particles and zero bonds. This is the OFF-identity contract.

    When enabled, it adds:
      * ``sf_actin`` + ``sf_xlink_head`` particle types,
      * the four ``sf_`` bond types (see :func:`sf_bond_type_names`),
      * per-bundle: backbone chain bonds, two FA-anchor bonds, α-actinin
        intra + attach bonds (sarcomeric banding).

    Args:
        base_snap: a ``gsd.hoomd.Frame``-like snapshot (the current cell state).
        p: resolved SF parameters.
        fa_endpoint_positions: (M, 3) FA anchor positions (REQUIRED when enabled
            and ``n_SF > 0``; this compartment REQUIRES the fa compartment).
        fa_endpoint_tags: (M,) FA anchor global particle tags.
        rng: optional RNG.

    Returns:
        The same ``base_snap`` (disabled) or a new extended ``gsd.hoomd.Frame``.

    Raises:
        ValueError: if enabled with ``n_SF > 0`` but FA endpoints are not given.
    """
    # --- OFF-identity early return ---
    if (not p.enabled) or p.n_SF == 0:
        return base_snap

    if fa_endpoint_positions is None or fa_endpoint_tags is None:
        raise ValueError(
            "ventral_stress_fibers requires the fa compartment: pass "
            "fa_endpoint_positions + fa_endpoint_tags (FA clutch anchors). "
            "This module does not invent substrate anchors."
        )

    import gsd.hoomd

    if rng is None:
        rng = np.random.default_rng(p.seed)

    snap_old = base_snap
    n_part_old = int(snap_old.particles.N)

    layout = generate_stress_fiber_layout(
        p,
        fa_endpoint_positions,
        fa_endpoint_tags,
        particle_tag_start=n_part_old,
        rng=rng,
    )

    # Totals.
    n_new_actin = sum(int(a.shape[0]) for a in layout.actin_tags)
    n_new_heads = sum(int(h.shape[0]) for h in layout.xlink_head_tags)
    n_new_particles = n_new_actin + n_new_heads

    snap = gsd.hoomd.Frame()
    snap.particles.N = n_part_old + n_new_particles

    # ---- particle types ----
    old_types = list(snap_old.particles.types) if snap_old.particles.types else []
    new_particle_types = list(old_types)
    for t in ("sf_actin", "sf_xlink_head"):
        if t not in new_particle_types:
            new_particle_types.append(t)
    sf_actin_tid = new_particle_types.index("sf_actin")
    sf_head_tid = new_particle_types.index("sf_xlink_head")
    snap.particles.types = new_particle_types

    # ---- typeids ----
    typeids = np.empty(snap.particles.N, dtype=np.uint32)
    if n_part_old > 0:
        typeids[:n_part_old] = np.asarray(snap_old.particles.typeid)
    # appended block: actin beads then heads, per bundle in layout order.
    cursor = n_part_old
    for b in range(p.n_SF):
        na = int(layout.actin_tags[b].shape[0])
        nh = int(layout.xlink_head_tags[b].shape[0])
        typeids[cursor:cursor + na] = sf_actin_tid
        cursor += na
        typeids[cursor:cursor + nh] = sf_head_tid
        cursor += nh
    snap.particles.typeid = typeids

    # ---- positions ----
    pos_new = np.empty((snap.particles.N, 3), dtype=np.float64)
    if n_part_old > 0:
        pos_new[:n_part_old] = np.asarray(snap_old.particles.position)
    cursor = n_part_old
    for b in range(p.n_SF):
        beads = layout.actin_positions[b]
        heads = layout.xlink_head_positions[b]
        na, nh = beads.shape[0], heads.shape[0]
        pos_new[cursor:cursor + na] = beads
        cursor += na
        pos_new[cursor:cursor + nh] = heads
        cursor += nh
    snap.particles.position = pos_new

    # ---- masses ----
    mass_new = np.empty(snap.particles.N, dtype=np.float64)
    if n_part_old > 0:
        mass_new[:n_part_old] = np.asarray(snap_old.particles.mass)
    mass_new[n_part_old:] = 1.0
    snap.particles.mass = mass_new

    # ---- bond types ----
    old_bond_types = list(snap_old.bonds.types) if snap_old.bonds.types else []
    new_bond_types = list(old_bond_types)
    for name in sf_bond_type_names():
        if name not in new_bond_types:
            new_bond_types.append(name)
    tid_chain = new_bond_types.index(BOND_TYPE_SF_ACTIN)
    tid_anchor = new_bond_types.index(BOND_TYPE_SF_ANCHOR)
    tid_intra = new_bond_types.index(BOND_TYPE_SF_XLINK_INTRA)
    tid_attach = new_bond_types.index(BOND_TYPE_SF_XLINK_ATTACH)

    # ---- old bonds ----
    if int(snap_old.bonds.N) > 0:
        old_bg = np.asarray(snap_old.bonds.group, dtype=np.uint32).reshape(-1, 2)
        old_bt = np.asarray(snap_old.bonds.typeid, dtype=np.uint32)
    else:
        old_bg = np.empty((0, 2), dtype=np.uint32)
        old_bt = np.empty((0,), dtype=np.uint32)

    # ---- new bonds ----
    new_groups: list[tuple[int, int]] = []
    new_btids: list[int] = []
    for b in range(p.n_SF):
        bead_tags = layout.actin_tags[b]
        head_tags = layout.xlink_head_tags[b]
        fa_a, fa_b = int(layout.fa_endpoints[b, 0]), int(layout.fa_endpoints[b, 1])
        nb = int(bead_tags.shape[0])

        # backbone chain
        for i in range(nb - 1):
            new_groups.append((int(bead_tags[i]), int(bead_tags[i + 1])))
            new_btids.append(tid_chain)
        # FA anchors: bead 0 ↔ FA_A, last bead ↔ FA_B
        new_groups.append((int(bead_tags[0]), fa_a))
        new_btids.append(tid_anchor)
        new_groups.append((int(bead_tags[nb - 1]), fa_b))
        new_btids.append(tid_anchor)
        # α-actinin: per period one intra (head pair) + two attach (head→bead)
        n_sarc = int(layout.n_sarc[b])
        for s in range(n_sarc):
            h0 = int(head_tags[2 * s])
            h1 = int(head_tags[2 * s + 1])
            new_groups.append((h0, h1))
            new_btids.append(tid_intra)
            # nearest backbone bead to this band centre (band centre is at
            # fractional position (s+0.5)/n_sarc → nearest bead index).
            frac = (s + 0.5) / n_sarc
            ib = int(min(nb - 1, max(0, round(frac * (nb - 1)))))
            new_groups.append((h0, int(bead_tags[ib])))
            new_btids.append(tid_attach)
            new_groups.append((h1, int(bead_tags[ib])))
            new_btids.append(tid_attach)

    if new_groups:
        new_bg = np.asarray(new_groups, dtype=np.uint32).reshape(-1, 2)
        new_bt = np.asarray(new_btids, dtype=np.uint32)
        snap.bonds.group = np.concatenate([old_bg, new_bg], axis=0)
        snap.bonds.typeid = np.concatenate([old_bt, new_bt], axis=0)
    else:
        snap.bonds.group = old_bg
        snap.bonds.typeid = old_bt
    snap.bonds.N = int(snap.bonds.group.shape[0])
    snap.bonds.types = new_bond_types

    # ---- pass through angles ----
    if int(snap_old.angles.N) > 0:
        snap.angles.N = int(snap_old.angles.N)
        snap.angles.types = list(snap_old.angles.types)
        snap.angles.typeid = np.asarray(snap_old.angles.typeid)
        snap.angles.group = np.asarray(snap_old.angles.group)

    snap.configuration.box = list(snap_old.configuration.box)

    # Stash the layout for the Lead (wiring myosin / measuring tension).
    return snap


# ===========================================================================
# Bond-param registration
# ===========================================================================
def register_stress_fiber_bond_params(
    bond: md.bond.Harmonic, p: ResolvedStressFibers, layout: StressFiberLayout
) -> None:
    """Wire ``md.bond.Harmonic`` params for the four ``sf_`` bond types.

    The backbone ``sf_actin_bond`` uses a SINGLE rest length: the mean bundle
    bead spacing (bundles built from FA→FA spans of similar length share a
    rest length; per-bundle ℓ0 variation is small for a basal layout). For a
    production build with widely varying bundle lengths the Lead should use a
    per-r0 binned family (TODO), mirroring the cortex attach binning.

    Raises:
        NotImplementedError: if ``k_actin`` / ``k_anchor`` are PI-flagged None.
    """
    if p.k_actin is None or p.k_anchor is None:
        raise NotImplementedError(
            "register_stress_fiber_bond_params needs k_actin and k_anchor, "
            "which are PI-flagged None (see PI_DECISIONS). Set ratified values "
            "in the stress_fibers config before building the SF force law."
        )
    ell0 = (
        float(np.mean(layout.ell0_actin))
        if layout.ell0_actin.size > 0
        else 0.0
    )
    bond.params[BOND_TYPE_SF_ACTIN] = dict(k=p.k_actin, r0=ell0)
    # Anchor rest length ≈ 0: the SF end bead is placed AT the FA endpoint so
    # the anchor is force-free at construction (physiological-baseline rule).
    bond.params[BOND_TYPE_SF_ANCHOR] = dict(k=p.k_anchor, r0=0.0)
    bond.params[BOND_TYPE_SF_XLINK_INTRA] = dict(k=p.k_xl, r0=p.alpha_length)
    # Attach r0 = 0: head placed at the band centre, bonded to the nearest
    # bead; small residual stretch is force-negligible at k_xl = 1e-7 N/m.
    bond.params[BOND_TYPE_SF_XLINK_ATTACH] = dict(k=p.k_xl, r0=0.0)


# ===========================================================================
# Basal observable: SF axial tension (DENYLISTED from γ)
# ===========================================================================
def measure_sf_tension(
    positions_by_tag: np.ndarray,
    bond_group: np.ndarray,
    bond_typeid: np.ndarray,
    bond_types: list[str],
    p: ResolvedStressFibers,
    *,
    r0: float | None = None,
) -> dict[str, float]:
    """Mean axial tension of the ``sf_actin_bond`` backbone (basal observable).

    This is the SF analogue of the single-SF force band (Kumar 2006 ~10-30 nN).
    It is summed ONLY over the ``sf_actin_bond`` load path and is NEVER part of
    the cortical-tension γ (the bond type is ``sf_``-prefixed → denylisted).

    Args:
        positions_by_tag: (N, 3) positions indexed by particle tag.
        bond_group: (B, 2) bond endpoint tags.
        bond_typeid: (B,) per-bond type id.
        bond_types: bond-type name list (type-id order).
        p: resolved SF parameters (provides ``k_actin``).
        r0: construction rest length [m] — the bond's registered ``r0``
            (``mean(layout.ell0_actin)``). REQUIRED for a trustworthy tension on a
            uniformly contracted bundle; if ``None`` it falls back to the live mean
            bond length and sets ``r0_is_live=1.0`` in the result.

    Returns:
        dict with ``mean_tension_N``, ``max_tension_N``, ``n_bonds``, ``in_band``
        (whether mean is inside ``p.sf_tension_band_N``), and ``r0_is_live``.

    Raises:
        NotImplementedError: if ``k_actin`` is PI-flagged None.
    """
    if p.k_actin is None:
        raise NotImplementedError(
            "measure_sf_tension needs k_actin (PI-flagged None); set a ratified "
            "value before measuring SF tension."
        )
    pos = np.asarray(positions_by_tag, dtype=np.float64)
    bg = np.asarray(bond_group, dtype=np.int64).reshape(-1, 2)
    bt = np.asarray(bond_typeid)
    try:
        chain_tid = bond_types.index(BOND_TYPE_SF_ACTIN)
    except ValueError:
        return dict(mean_tension_N=0.0, max_tension_N=0.0, n_bonds=0.0, in_band=0.0)
    mask = bt == chain_tid
    sel = bg[mask]
    if sel.shape[0] == 0:
        return dict(mean_tension_N=0.0, max_tension_N=0.0, n_bonds=0.0, in_band=0.0)
    dr = pos[sel[:, 0]] - pos[sel[:, 1]]
    r = np.linalg.norm(dr, axis=1)
    # Reference rest length r0 MUST be the CONSTRUCTION rest length (the bond's
    # registered r0 = mean ell0_actin, see register_stress_fiber_bond_params),
    # NOT the live mean bond length. Using the live mean would make a uniformly
    # contracted bundle (r approx constant) report ~0 tension — exactly the
    # physiological load case we want to measure. Caller passes the registered
    # r0; if omitted we fall back to the live mean but flag it via r0_is_live.
    r0_is_live = r0 is None
    if r0 is None:
        r0 = float(np.mean(r))
    tension = p.k_actin * np.clip(r - float(r0), 0.0, None)
    mean_T = float(np.mean(tension))
    lo, hi = p.sf_tension_band_N
    return dict(
        mean_tension_N=mean_T,
        max_tension_N=float(np.max(tension)),
        n_bonds=float(sel.shape[0]),
        in_band=float(lo <= mean_T <= hi),
        # 1.0 when r0 fell back to the live mean (under-reports uniform tension —
        # pass the registered construction r0 for the trustworthy number).
        r0_is_live=float(r0_is_live),
    )
